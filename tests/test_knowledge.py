"""The knowledge folders under plugins/anthology/knowledge/ (Part 1 section 6).

Shared by Tasks 3-6. Each folder is generated by `vendor.py`; these tests check the
shape of what is committed. A folder that has not landed yet has its own
`@unittest.expectedFailure` test below: the task that lands it deletes that marker
(leaving the marker in place makes the run fail with an "unexpected success").
"""
import re
import unittest

from _repo import KNOWLEDGE, STRIPPED_KNOWLEDGE, load_frontmatter

UNCHANGED = {"frontend-design", "web-design-guidelines", "design-skills"}
EXPECTED_KNOWLEDGE = set(STRIPPED_KNOWLEDGE) | UNCHANGED | {
    "ui-taste", "caveman", "design-taste-frontend"}
FORBIDDEN_IN_STRIPPED = ("~~", "CONNECTORS.md", "uxkin.com/mcp", "find_ui_materials",
                         "find_ui_references", "ui-design-mcp", "SUPERCHARGED")
# "If the UXKIN tools are connected ..." lead-ins; "If no tool is connected" and "If tools are
# not connected" are fallbacks and stay.
CONNECTED_LEAD_IN = re.compile(
    r"^\s*(?:[-*+]\s+)?(?:\*\*)?If\s+(?!no\b).*\btools?\s+(?:is|are|weren't|were)\s+connected\b",
    re.MULTILINE)


def present():
    return {p.name for p in KNOWLEDGE.iterdir() if p.is_dir()}


def skill_files(folder):
    """The SKILL.md files of a folder; design-skills is a repo of skills, not one skill."""
    if folder == "design-skills":
        return sorted((KNOWLEDGE / folder / "skills").glob("*/SKILL.md"))
    return [KNOWLEDGE / folder / "SKILL.md"]


class KnowledgeFoldersTest(unittest.TestCase):
    def test_expected_set_is_the_22_plus_the_other_six(self):
        self.assertEqual(len(STRIPPED_KNOWLEDGE), 22)
        self.assertEqual(len(EXPECTED_KNOWLEDGE), 28)

    def test_no_unexpected_folders(self):
        self.assertEqual(present() - EXPECTED_KNOWLEDGE, set())

    def test_every_landed_folder_is_there(self):
        landed = EXPECTED_KNOWLEDGE - {"ui-taste", "caveman", "design-taste-frontend"}
        self.assertEqual(landed - present(), set())

    # Delete the marker from a test when its task lands the folder.
    @unittest.expectedFailure
    def test_ui_taste_lands_in_task_4(self):
        self.assertIn("ui-taste", present())

    @unittest.expectedFailure
    def test_caveman_lands_in_task_4(self):
        self.assertIn("caveman", present())

    @unittest.expectedFailure
    def test_design_taste_frontend_lands_in_task_5(self):
        self.assertIn("design-taste-frontend", present())

    def test_every_skill_has_its_folder_name_and_a_description(self):
        for folder in sorted(present() & EXPECTED_KNOWLEDGE):
            files = skill_files(folder)
            self.assertTrue(files, folder)
            for path in files:
                self.assertTrue(path.is_file(), path)
                meta, body = load_frontmatter(path)
                self.assertEqual(meta.get("name"), path.parent.name, path)
                self.assertTrue(str(meta.get("description", "")).strip(), path)
                self.assertTrue(body.strip(), path)

    def test_the_22_have_no_connector_leftovers(self):
        for folder in sorted(STRIPPED_KNOWLEDGE):
            root = KNOWLEDGE / folder
            self.assertTrue(root.is_dir(), folder)
            self.assertFalse(list(root.rglob("CONNECTORS.md")), folder)
            for path in sorted(p for p in root.rglob("*") if p.is_file()):
                text = path.read_text(encoding="utf-8", errors="ignore")
                for needle in FORBIDDEN_IN_STRIPPED:
                    self.assertNotIn(needle, text, f"{path.relative_to(KNOWLEDGE)}: {needle}")
                self.assertIsNone(CONNECTED_LEAD_IN.search(text), f"{path.relative_to(KNOWLEDGE)}")

    def test_the_connected_lead_in_pattern_only_matches_the_connector_blocks(self):
        for yes in ("If the UXKIN tools are connected:", "- If project management tool is connected, x",
                    "**If tool is connected:**", "If the UXKIN tools weren't connected and"):
            self.assertTrue(CONNECTED_LEAD_IN.search(yes), yes)
        for no in ("If no project management tool is connected:", "**If tools are not connected:**",
                   "If these tools are not connected, work from what the user provides."):
            self.assertIsNone(CONNECTED_LEAD_IN.search(no), no)

    def test_code_review_checklist_never_points_at_the_builtin_command(self):
        text = (KNOWLEDGE / "code-review-checklist" / "SKILL.md").read_text(encoding="utf-8")
        self.assertEqual(re.findall(r"/code-review(?!-checklist)", text), [])
        self.assertIn("code-review-checklist", text)


if __name__ == "__main__":
    unittest.main()
