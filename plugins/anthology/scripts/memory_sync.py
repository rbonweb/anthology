def note_sources(root, home):
    """`[(scope, dir)]` of the existing note folders: repo, each agent, personal (for the
    indexer). `root` may be None (personal only)."""
    out = []
    if root is not None:
        repo = Path(str(root)) / ".claude" / "memory"
        if repo.is_dir() and not repo.is_symlink():
            out.append(("repo", repo))
        agents = Path(str(root)) / ".claude" / "agent-memory"
        if agents.is_dir() and not agents.is_symlink():
            for d in sorted(agents.iterdir()):
                if d.is_dir() and not d.is_symlink():
                    out.append(("agent", d))
    personal = Path(str(home)) / "personal-memory"
    if personal.is_dir() and not personal.is_symlink():  # never indexed through a link (ADR-020)
        out.append(("personal", personal))
    return out


def _auto_memory_off(root, config, env):
    value = env.get("CLAUDE_CODE_DISABLE_AUTO_MEMORY")
    if value is not None and value.strip().lower() not in ("", "0", "false", "no"):
        return True
    paths = []
    if root is not None:
        paths += [root / ".claude" / "settings.local.json", root / ".claude" / "settings.json"]
    paths.append(config / "settings.json")
    for path in paths:
        data = _load_settings(path)
        if data and "autoMemoryEnabled" in data:
            return data["autoMemoryEnabled"] is False
    return False


def _section(title, directory, text):
    return "## %s (%s)\n\n%s" % (title, directory, text if text.endswith("\n") else text + "\n")


def _context_index(directory, exclude_types=()):
    """The index of `directory` for the session context: rendered within the (small) context
    budget, with "N more" pointers that name the full on-disk MEMORY.md."""
    suffix = " (full index: %s)" % (Path(directory) / "MEMORY.md")
    text = render_index(directory, CONTEXT_SECTION_BUDGET, suffix, exclude_types=exclude_types)
    if text is not None:
        return "" if text.strip() == GENERATED else text
    try:  # no notes: show an existing hand-made index, within the same budget
        raw = (Path(directory) / "MEMORY.md").read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    return "\n".join(raw.splitlines()[:CONTEXT_SECTION_BUDGET.lines])[:CONTEXT_SECTION_BUDGET.bytes] + "\n"


def _personal_unsafe(personal, messages):
    """True (and one visible message) if the personal-memory folder is a symlink or not a folder.
    Fail closed (m8): nothing is moved into, copied into, regenerated in or read through it,
    because a quiet skip leaves `user` notes in the repo with no sign."""
    if not _unsafe_dir(personal):
        return False
    msg = ("anthology memory: %s is a symlink or not a folder, so personal memory was not "
           "loaded, user notes were not moved out of the repo and old notes were not copied; "
           "make it a real folder to turn this back on" % personal)
    if msg not in messages:
        messages.append(msg)
    return True


def _sync_repo(root, home, config, env, messages):
    """The approved-repo flow. Returns the same-session cover section, or None."""
    claude = root / ".claude"
    repo_mem = claude / "memory"
    if claude.is_symlink():
        messages.append("anthology memory: .claude is a symlink; repo memory skipped")
        return None
    if repo_mem.is_symlink() or (os.path.lexists(str(repo_mem)) and not repo_mem.is_dir()):
        messages.append("anthology memory: .claude/memory is a symlink or not a folder; "
                        "repo memory skipped")
        return None
    personal = home / "personal-memory"
    personal_ok = not _personal_unsafe(personal, messages)
    copied, conflicts = 0, 0
    for old in legacy_dirs(root, config, env=env) if personal_ok else ():
        # Never into the repo on its own: setup moves chosen notes there (B3).
        res = migrate(old, None, personal, ledger=home / "migrated.json")
        copied += len(res["copied"])
        conflicts += len(res["conflicts"])
    if copied:
        messages.append("anthology memory: copied %d note(s) from the old per-path memory folder "
                        "into personal memory (%s); /anthology:setup can move chosen ones into "
                        "this repo's memory" % (copied, personal))
    if conflicts:
        messages.append("anthology memory: %d migrated note(s) differ from existing ones; kept "
                        "side by side as *.migrated-*.md" % conflicts)
    agents = claude / "agent-memory"
    agent_dirs = []
    if agents.is_dir() and not agents.is_symlink():
        agent_dirs = [d for d in sorted(agents.iterdir()) if d.is_dir() and not d.is_symlink()]
    moved, side = 0, 0
    for d in ([repo_mem] + agent_dirs) if personal_ok else ():  # `user` notes never stay in the repo (C1)
        res = sweep_user_notes(d, personal)
        moved += len(res["moved"])
        side += len(res["conflicts"])
        if res["moved"] and not _list_notes(d) and _lstat_kind(d / "MEMORY.md") == "file":
            _atomic_write(d / "MEMORY.md", (GENERATED + "\n").encode("utf-8"))  # no stale entries
    if moved:
        messages.append("anthology memory: moved %d user note(s) out of the repo into personal "
                        "memory (%s)%s; if they were committed, commit their removal"
                        % (moved, personal, "; %d kept side by side as *.migrated-*.md" % side
                           if side else ""))
    settings = claude / "settings.local.json"
    changed = False
    if settings_tracked(root, env=env):
        messages.append("anthology memory: .claude/settings.local.json is tracked by git, so "
                        "anthology did not write this clone's memory path into it; untrack it "
                        "with `git rm --cached .claude/settings.local.json`")
    elif _load_settings(settings) is None:
        messages.append("anthology memory: .claude/settings.local.json is not a valid JSON "
                        "object; left untouched, so autoMemoryDirectory is not set")
    else:
        _data, changed = ensure_memory_dir(root, settings)
        try:
            ensure_ignored(root, env=env)
        except UnsafeTarget as exc:
            messages.append("anthology memory: could not git-ignore settings.local.json: %s" % exc)
    regenerate_index(repo_mem, exclude_types=REPO_EXCLUDE)
    for d in agent_dirs:
        regenerate_index(d, exclude_types=REPO_EXCLUDE)
    if not changed:
        return None
    messages.append(DIR_SET)
    text = _context_index(repo_mem, exclude_types=REPO_EXCLUDE)
    return _section("Repo memory", repo_mem, text.strip() and text or "(no notes yet)\n")


def _run(cwd, env):
    config = config_dir(env)
    home = config / "anthology"
    root = repo_root(cwd, env=env)
    if _auto_memory_off(root, config, env):
        return "", []
    messages = []
    cover = None
    if root is not None:
        if is_approved(repo_key(root, env=env), env=env):
            try:
                cover = _sync_repo(root, home, config, env, messages)
            except Exception as exc:  # the personal section below must still be built
                messages.append("anthology memory: repo memory step failed: %s"
                                % (str(exc) or type(exc).__name__)[:120])
        elif (root / ".claude" / "memory").is_dir() or (root / ".claude" / "agent-memory").is_dir():
            messages.append(HINT)
    personal = home / "personal-memory"
    text = ""
    unsafe = _personal_unsafe(personal, messages)
    if unsafe:
        text = ""
    elif personal.is_dir():
        try:
            regenerate_index(personal)
            text = _context_index(personal)
        except OSError as exc:
            messages.append("anthology memory: personal memory index: %s" % exc.strerror)
    # Always shown, with its path, even when empty or missing (the folder is not created here).
    if unsafe:
        sections = ["## Personal memory\n" + PERSONAL_UNAVAILABLE % personal + "\n"]
    else:
        sections = ["## Personal memory (%s)\n%s\n\n%s" % (
            personal, PERSONAL_SAVE % personal, text if text.strip() else "(no notes yet)\n")]
    if cover:
        sections.append(cover)
    return "\n".join(sections), messages


def run(cwd, env=None):
    """SessionStart entry point: `(context_text, messages)`. Never raises."""
    try:
        return _run(cwd, dict(os.environ) if env is None else dict(env))
    except Exception as exc:  # a memory problem must never fail a session
        return "", ["anthology memory: %s" % (str(exc) or type(exc).__name__)[:120]]
