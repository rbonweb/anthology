class SaveError(ValueError):
    """A note `save` refused (bad argument, unsafe path, existing note, secret)."""


def _has_control(text, allowed=""):
    """Control characters (category Cc), except those in `allowed`."""
    return any(unicodedata.category(c) == "Cc" and c not in allowed for c in text)


def _has_hidden(text):
    """Controls, format characters (bidi overrides, zero-width) and line/paragraph separators."""
    return any(unicodedata.category(c) in ("Cc", "Cf", "Zl", "Zp") for c in text)


def _check_line(label, value, limit):
    if not isinstance(value, str):
        raise SaveError("%s must be text" % label)
    value = value.strip()
    if not value:
        raise SaveError("%s must not be empty" % label)
    if len(value) > limit:
        raise SaveError("%s is too long (at most %d characters)" % (label, limit))
    if _has_hidden(value):
        raise SaveError("%s must be one line without control or invisible formatting "
                        "characters" % label)
    return value


def _check_body(value):
    if not isinstance(value, str):
        raise SaveError("body must be text")
    value = value.replace("\r\n", "\n").replace("\r", "\n")
    if _has_control(value, "\n\t"):
        raise SaveError("body must not contain control characters (other than newline and tab)")
    value = _LEADING_BLANK_LINES.sub("", value).rstrip()
    if not value:
        raise SaveError("body must not be empty")
    if len(value.encode("utf-8")) > MAX_BODY_BYTES:
        raise SaveError("body is too long (at most %d bytes)" % MAX_BODY_BYTES)
    return value + "\n"


_SECRET_FIELDS = ("slug", "name", "description", "body")


def _secret_findings(texts):
    """`[(field index, label, line)]`, sorted and unique, for every `SECRET_PATTERNS` match in
    the fields joined by newlines (so a match that spans a field break is still found). The
    line is 1-based within the field; never the matched text."""
    joined = "\n".join(texts)
    starts, pos = [], 0
    for text in texts:
        starts.append(pos)
        pos += len(text) + 1
    found = set()
    for label, rx in memory_privacy.SECRET_PATTERNS:
        for m in rx.finditer(joined):
            idx = bisect.bisect_right(starts, m.start()) - 1
            found.add((idx, label, joined.count("\n", starts[idx], m.start()) + 1))
    return sorted(found)


_MAX_SECRET_FINDINGS = 5


def _describe_secrets(findings):
    """`url-credentials on line 3 of the note body, password in the name`: kinds and places,
    never the text. At most `_MAX_SECRET_FINDINGS` findings are listed, then `and N more`."""
    parts, groups = [], {}
    for idx, label, line in findings[:_MAX_SECRET_FINDINGS]:
        groups.setdefault((idx, label), []).append(line)
    for (idx, label), lines in groups.items():
        if _SECRET_FIELDS[idx] != "body":
            parts.append("%s in the %s" % (label, _SECRET_FIELDS[idx]))
        else:
            parts.append("%s on %s %s of the note body" % (
                label, "line" if len(lines) == 1 else "lines", ", ".join(str(n) for n in lines)))
    text = ", ".join(parts)
    if len(findings) > _MAX_SECRET_FINDINGS:
        text += " and %d more" % (len(findings) - _MAX_SECRET_FINDINGS)
    return text


def _refuse_secrets(texts, env):
    joined = "\n".join(texts)
    # memory_privacy.SECRET_PATTERNS is the one anthology-side list (a superset of G6, by a test)
    findings = _secret_findings(texts)
    if findings:
        raise SaveError("refusing to save: the note looks like it contains a secret; memory is "
                        "committed to the repo, so remove or replace that value (e.g. refer to "
                        "the env var name) and save again. Found: %s"
                        % _describe_secrets(findings))
    for var, value in sorted((os.environ if env is None else env).items()):
        if (isinstance(value, str) and len(value) >= 8 and _SECRET_ENV_NAME.search(var)
                and value in joined):
            raise SaveError("refusing to save: the note contains the value of $%s "
                            "(memory is committed to the repo)" % var)


def _privacy_check(texts):
    """The one privacy wiring point for `save`: refuse personal or private data (home paths,
    emails, private hosts/IPs, SSH key paths, token shapes) before a note is written into the
    repo. Uses `privacy_findings(text) -> list` (memory_privacy). The message names the kinds
    found (`memory_privacy.describe`), never the matched text."""
    for label, text in zip(("slug", "name", "description", "body"), texts):
        try:
            findings = privacy_findings(text)
        except Exception as exc:  # a scanner bug is a clean refusal, never a traceback or a write
            raise SaveError("refusing to save: the privacy scan failed (%s); nothing was written"
                            % type(exc).__name__)
        if findings:
            raise SaveError("refusing to save: the %s contains personal or private data (%s); "
                            "memory is committed to the repo, so keep that in personal memory"
                            % (label, memory_privacy.describe(findings)))


def _yaml_quote(value):
    return "'" + value.replace("'", "''") + "'"


def _ensure_real_dir(path, root):
    """Make `path` a real directory (never a symlink), creating it if absent."""
    rel = path.relative_to(root).as_posix()
    if not os.path.lexists(str(path)):
        try:
            os.mkdir(str(path), 0o755)
        except FileExistsError:
            pass
        except OSError as exc:
            raise SaveError("could not create %s: %s" % (rel, exc.strerror or exc))
    if os.path.islink(str(path)) or not os.path.isdir(str(path)):
        raise SaveError("refusing to write: %s is a symlink or not a folder" % rel)


def save_note(root, agent, type_, slug, name, description, body, replace=False, today=None,
              env=None):
    """Write `<root>/.claude/agent-memory/anthology-<agent>/<type_>-<slug>.md` and regenerate that
    folder's MEMORY.md.

    Only validated parts build the path, so no argument can reach outside the agent's folder.
    An existing note is refused unless `replace`; symlinks are never written through. Returns
    {"path", "relative", "root", "action" ("created" or "replaced"), "index_warning"}; raises
    SaveError. A slug that starts with `<type_>-` loses that prefix, so the file is never
    `project-project-x.md`."""
    if agent not in ROSTER:
        raise SaveError("unknown agent; use one of: %s" % ", ".join(ROSTER))
    if type_ not in SAVE_TYPES:
        raise SaveError("type must be one of: %s" % ", ".join(SAVE_TYPES))
    if not (isinstance(slug, str) and SLUG_RE.fullmatch(slug) and len(slug) <= MAX_SLUG):
        raise SaveError("slug must be lowercase words joined by single dashes (a-z, 0-9), "
                        "at most %d characters" % MAX_SLUG)
    name = _check_line("name", name, MAX_NAME)
    description = _check_line("description", description, MAX_DESCRIPTION)
    body = _check_body(body)
    _refuse_secrets((slug, name, description, body), env)
    _privacy_check((slug, name, description, body))
    if slug.startswith(type_ + "-") and len(slug) > len(type_) + 1:
        slug = slug[len(type_) + 1:]  # `--type project --slug project-x` is project-x.md
    if not os.path.isdir(str(root)):
        raise SaveError("not a folder: %s" % root)
    root = Path(os.path.realpath(str(root)))

    agent_dir = root / ".claude" / "agent-memory" / ("anthology-%s" % agent)
    for directory in (root / ".claude", root / ".claude" / "agent-memory", agent_dir):
        _ensure_real_dir(directory, root)
    if os.path.realpath(str(agent_dir)) != str(agent_dir):
        raise SaveError("refusing to write: %s is a symlink or not a folder"
                        % agent_dir.relative_to(root).as_posix())

    path = agent_dir / ("%s-%s.md" % (type_, slug))
    relative = path.relative_to(root).as_posix()
    text = ("---\nname: %s\ndescription: %s\nmetadata:\n  type: %s\n  modified: %s\n---\n\n%s"
            % (_yaml_quote(name), _yaml_quote(description), type_,
               str(today or datetime.date.today().isoformat()), body))
    data = text.encode("utf-8")
    action = "created"
    try:
        if not replace:
            try:
                fd = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_EXCL | _O_NOFOLLOW, 0o644)
            except FileExistsError:
                raise SaveError("%s already exists; pass --replace to overwrite it" % relative)
            try:
                with os.fdopen(fd, "wb") as fh:
                    fh.write(data)
            except BaseException:
                try:
                    os.unlink(str(path))
                except OSError:
                    pass
                raise
        else:
            kind = _lstat_kind(path)
            if kind == "other":
                raise SaveError("refusing to write: %s is a symlink or not a regular file"
                                % relative)
            action = "replaced" if kind == "file" else "created"
            _atomic_write(path, data)
    except UnsafeTarget as exc:
        raise SaveError(str(exc))
    except OSError as exc:
        raise SaveError("could not write %s: %s" % (relative, exc.strerror or exc))

    warning = None
    try:
        regenerate_index(agent_dir, exclude_types=REPO_EXCLUDE)
    except (OSError, UnsafeTarget) as exc:
        warning = str(exc)
    return {"path": path, "relative": relative, "root": root, "action": action,
            "index_warning": warning}


