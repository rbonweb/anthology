def _load_ledger(ledger):
    try:
        data = json.loads(Path(ledger).read_text(encoding="utf-8"))
        return {h for h in data.get("done", []) if isinstance(h, str)}
    except (OSError, ValueError, AttributeError):
        return set()


def _is_plain(path):
    return os.path.isfile(str(path)) and not os.path.islink(str(path))


def _create_exclusive(path, data):
    """Create `path` with `data`, never replacing anything; False if the name is taken."""
    try:
        with open(str(path), "xb") as fh:
            fh.write(data)
        return True
    except FileExistsError:
        return False


def _unsafe_dir(path):
    """True if `path` is a symlink or exists as something other than a folder."""
    path = Path(path)
    return path.is_symlink() or (os.path.lexists(str(path)) and not path.is_dir())


def _ensure_private_dir(path):
    """Create a missing personal-memory folder as 0700 (it holds notes about the user)."""
    path = Path(path)
    if not os.path.lexists(str(path)):
        path.mkdir(parents=True, exist_ok=True)
        os.chmod(str(path), 0o700)


def _same_copy(dest_dir, name, data):
    """The plain file in `dest_dir` that holds exactly `data`: `name` itself or an earlier
    `<stem>.migrated-*.md` copy; None if there is none."""
    dest_dir = Path(dest_dir)
    stem = name[:-3]
    try:
        names = sorted(os.listdir(str(dest_dir)))
    except OSError:
        return None
    for c in [name] + [c for c in names if c.startswith(stem + ".migrated-") and c.endswith(".md")]:
        try:
            if _is_plain(dest_dir / c) and (dest_dir / c).read_bytes() == data:
                return dest_dir / c
        except OSError:
            continue
    return None


def placement_status(dest_dir, name, data):
    """What copying `data` as `name` into `dest_dir` would do, without writing: `new`,
    `identical` (the note, or an earlier side-by-side copy, already holds these bytes) or
    `conflict` (a different note has the name; a `<stem>.migrated-<date>.md` copy is made)."""
    if not os.path.lexists(str(Path(dest_dir) / name)):
        return "new"
    return "identical" if _same_copy(dest_dir, name, data) else "conflict"


def side_by_side_name(dest_dir, name, date):
    """The first free `<stem>.migrated-<date>[-N].md` name in `dest_dir` (the copy a conflict
    gets; setup's preview shows the same name)."""
    stem, n = name[:-3], 1
    while True:
        candidate = "%s.migrated-%s%s.md" % (stem, date, "" if n == 1 else "-%d" % n)
        if not os.path.lexists(str(Path(dest_dir) / candidate)):
            return candidate
        n += 1


def _place(dest_dir, name, data, date):
    """Copy `data` into `dest_dir` as `name`, never overwriting: a different file with the name
    gets a `<stem>.migrated-<date>.md` copy instead. Returns `(status, path)`, status `created`,
    `identical` or `conflict`; `path` is the file that now holds `data`."""
    dest_dir = Path(dest_dir)
    if _create_exclusive(dest_dir / name, data):
        return "created", dest_dir / name
    same = _same_copy(dest_dir, name, data)
    if same:
        return "identical", same
    while True:
        path = dest_dir / side_by_side_name(dest_dir, name, date)
        if _create_exclusive(path, data):
            return "conflict", path


def legacy_entries(old_dir):
    """`[(file name, bytes)]` of the notes in an old path-keyed memory folder: flat `*.md`
    files except `MEMORY.md`; symlinks and non-regular files are skipped."""
    out = []
    old = Path(old_dir)
    if not old.is_dir():
        return out
    for entry in sorted(os.scandir(str(old)), key=lambda e: e.name):
        if not entry.name.endswith(".md") or entry.name == "MEMORY.md":
            continue
        try:
            if entry.is_symlink() or not entry.is_file(follow_symlinks=False):
                continue
            out.append((entry.name, Path(entry.path).read_bytes()))
        except OSError:
            continue
    return out


def note_info(name, data):
    """Parsed frontmatter (`name`, `description`, `type`, ...) of a note's bytes."""
    return memory_index.parse_text(data.decode("utf-8", errors="replace"), name[:-3])


def promotion_block(info, data, home=None, hostname=None):
    """`(findings, reason)`: why a note may not go into repo memory, or `([], None)`."""
    if is_user_note(info):
        return [], USER_REASON
    findings = privacy_findings(data.decode("utf-8", errors="replace"), home=home, hostname=hostname)
    if findings:
        return findings, ("the privacy scan found %s; kept in personal memory"
                          % memory_privacy.describe(findings))
    return [], None


def migrate(old_dir, repo_mem, personal_mem, ledger=None, today=None, promote=(), home=None,
            hostname=None):
    """Copy the notes of an old path-keyed memory folder into personal memory (`personal_mem`).
    Nothing goes into the repo on its own: only a note named in `promote` (an explicit choice
    in setup) goes to `repo_mem`, and only if it is not `type: user` and the privacy scan finds
    nothing; otherwise it stays personal and is listed in `blocked`.

    Never overwrites: a different file with the same name gets a `<stem>.migrated-<date>.md`
    copy. `ledger` (a JSON file) remembers what was handled so a note deleted later is not
    copied again; it governs the automatic copy only (a promoted note is copied even if the
    ledger has it). Symlinked or non-folder destinations are never written through. Returns
    `{"copied", "skipped", "conflicts", "promoted", "blocked"}`: file names, except `blocked`
    (`{"file", "findings", "reason"}`); `promoted` names the notes now in repo memory."""
    result = {"copied": [], "skipped": [], "conflicts": [], "promoted": [], "blocked": []}
    entries = legacy_entries(old_dir)
    if not entries:
        return result
    date = today or datetime.date.today().isoformat()
    done = _load_ledger(ledger) if ledger else set()
    handled = set(done)
    for name, data in entries:
        sha = hashlib.sha256(data).hexdigest()
        to_repo = False
        if name in promote:
            findings, reason = promotion_block(note_info(name, data), data, home, hostname)
            if reason is None and (repo_mem is None or _unsafe_dir(repo_mem)
                                   or _unsafe_dir(Path(repo_mem).parent)):
                reason = ("repo memory (or .claude) is a symlink or not a folder; kept in "
                          "personal memory")
            if reason is None:
                to_repo = True
            else:
                result["blocked"].append({"file": name, "findings": findings, "reason": reason})
        if not to_repo and sha in done:
            result["skipped"].append(name)
            continue
        dest_dir = Path(repo_mem if to_repo else personal_mem)
        if _unsafe_dir(dest_dir):
            continue  # never write through a symlinked or non-folder destination
        if to_repo:
            dest_dir.mkdir(parents=True, exist_ok=True)
        else:
            _ensure_private_dir(dest_dir)
        status, _path = _place(dest_dir, name, data, date)
        result[{"created": "copied", "identical": "skipped", "conflict": "conflicts"}[status]].append(name)
        if to_repo:
            result["promoted"].append(name)
        handled.add(sha)
    if ledger and handled != done:
        _atomic_write(ledger, (json.dumps({"version": 1, "done": sorted(handled)}, indent=2)
                               + "\n").encode("utf-8"))
    return result


def _encode_project_path(path):
    return re.sub(r"[^A-Za-z0-9]", "-", os.path.realpath(str(path)))


def legacy_dirs(root, config, env=None):
    """The old path-keyed auto-memory folders of the repo at `root`
    (`<config>/projects/<encoded path>/memory`) for its work tree and its main work tree,
    deduplicated, in that order (they may not exist)."""
    out, seen = [], []
    for base in (root, _main_root(root, env=env)):
        base = Path(os.path.realpath(str(base)))
        if base in seen:
            continue
        seen.append(base)
        out.append(Path(str(config)) / "projects" / _encode_project_path(base) / "memory")
    return out


