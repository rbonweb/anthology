_DEFAULT_PORTS = ("22", "443", "80")
_SCP = re.compile(r"^(?:[^@/\s]+@)?([^:/\s]+):(.*)$")


def normalize_remote(url, base=None):
    """A stable key for a git remote URL (see the module docs): `host/owner/repo` lowercased,
    credentials and default ports dropped; a local path remote becomes `path:<realpath>`."""
    u = url.strip()
    path = None
    if u.lower().startswith("file://"):
        path = u[7:]
    elif "://" in u:
        rest = u.split("://", 1)[1]
        authority, _, tail = rest.partition("/")
        authority = authority.rsplit("@", 1)[-1]
        host, port = authority, ""
        if authority.count(":") == 1:
            host, port = authority.split(":")
        if port in _DEFAULT_PORTS:
            port = ""
        key = host + (":" + port if port else "") + "/" + tail
    elif u.startswith(("/", "./", "../", "~")):
        path = u
    else:
        m = _SCP.match(u)
        if m:
            key = m.group(1) + "/" + m.group(2)
        else:
            path = u
    if path is not None:
        full = os.path.realpath(os.path.join(str(base) if base else os.getcwd(),
                                             os.path.expanduser(path)))
        if full.endswith(".git"):
            full = full[:-4]
        return "path:" + full
    key = re.sub(r"/+", "/", key).rstrip("/")
    if key.endswith(".git"):
        key = key[:-4]
    return key.rstrip("/").lower()


def repo_key(root, env=None):
    """Identity of the repo at `root`: its normalised remote URL, else the path of the main
    work tree (`path:<realpath>`)."""
    out = _git_out(root, "remote", env=env)
    names = sorted(out.split()) if out else []
    if names:
        name = "origin" if "origin" in names else names[0]
        url = (_git_out(root, "remote", "get-url", name, env=env)
               or _git_out(root, "config", "--get", "remote.%s.url" % name, env=env))
        if url:
            return normalize_remote(url, base=root)
    return "path:" + str(_main_root(root, env=env))


def _approved_path(env=None):
    return anthology_home(env) / "approved-repos.json"


def _load_approved(env=None):
    try:
        data = json.loads(_approved_path(env).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        data = None
    repos = data.get("repos") if isinstance(data, dict) else None
    return {"version": 1, "repos": repos if isinstance(repos, dict) else {}}


def _save_approved(data, env=None):
    _atomic_write(_approved_path(env), (json.dumps(data, indent=2, sort_keys=True) + "\n").encode())


def is_approved(key, env=None):
    return key in _load_approved(env)["repos"]


def approve(root, env=None):
    """Approve the repo at `root` (and add the union merge attributes). Returns its key."""
    key = repo_key(root, env=env)
    data = _load_approved(env)
    if key not in data["repos"]:
        data["repos"][key] = {"approved": datetime.date.today().isoformat()}
        _save_approved(data, env)
    ensure_union_attrs(root)
    return key


def unapprove(key, env=None):
    data = _load_approved(env)
    if key not in data["repos"]:
        return False
    del data["repos"][key]
    _save_approved(data, env)
    return True


