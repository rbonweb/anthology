# Migration from the old path-keyed folder
# ---------------------------------------------------------------------------------------------


def _load_ledger(ledger):
    try:
        data = json.loads(Path(ledger).read_text(encoding="utf-8"))
        return {h for h in data.get("done", []) if isinstance(h, str)}
    except (OSError, ValueError, AttributeError):
        return set()


def _create_exclusive(path, data):
    """Create `path` with `data`, never replacing anything; False if the name is taken."""
    try:
        with open(str(path), "xb") as fh:
            fh.write(data)
        return True
    except FileExistsError:
        return False


def migrate(old_dir, repo_mem, personal_mem, ledger=None, today=None):
    """Copy the notes of an old path-keyed memory folder: `type: user` notes to `personal_mem`,
    the rest to `repo_mem`. Never overwrites: a different file with the same name gets a
    `<stem>.migrated-<date>.md` copy. `ledger` (a JSON file) remembers what was handled so a
    note deleted later is not copied again. Returns `{"copied", "skipped", "conflicts"}`."""
    result = {"copied": [], "skipped": [], "conflicts": []}
    old = Path(old_dir)
    if not old.is_dir():
        return result
    date = today or datetime.date.today().isoformat()
    done = _load_ledger(ledger) if ledger else set()
    handled = set(done)
    for entry in sorted(os.scandir(str(old)), key=lambda e: e.name):
        if not entry.name.endswith(".md") or entry.name == "MEMORY.md":
            continue
        try:
            if entry.is_symlink() or not entry.is_file(follow_symlinks=False):
                continue
            data = Path(entry.path).read_bytes()
        except OSError:
            continue
        sha = hashlib.sha256(data).hexdigest()
        if sha in done:
            result["skipped"].append(entry.name)
            continue
        stem = entry.name[:-3]
        info = memory_index.parse_text(data.decode("utf-8", errors="replace"), stem)
        dest_dir = Path(personal_mem if info["type"] == "user" else repo_mem)
        dest = dest_dir / entry.name
        dest_dir.mkdir(parents=True, exist_ok=True)
        if _create_exclusive(dest, data):
            result["copied"].append(entry.name)
        else:
            same = dest.is_file() and not dest.is_symlink() and dest.read_bytes() == data
            same = same or any(c.is_file() and not c.is_symlink() and c.read_bytes() == data
                               for c in dest_dir.glob(stem + ".migrated-*.md"))
            if same:
                result["skipped"].append(entry.name)
            else:
                n = 1
                while True:
                    suffix = "" if n == 1 else "-%d" % n
                    if _create_exclusive(dest_dir / ("%s.migrated-%s%s.md" % (stem, date, suffix)), data):
                        break
                    n += 1
                result["conflicts"].append(entry.name)
        handled.add(sha)
    if ledger and handled != done:
        _atomic_write(ledger, (json.dumps({"version": 1, "done": sorted(handled)}, indent=2)
                               + "\n").encode("utf-8"))
    return result


def _encode_project_path(path):
    return re.sub(r"[^A-Za-z0-9]", "-", os.path.realpath(str(path)))


