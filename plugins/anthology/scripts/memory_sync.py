def _list_notes(mem_dir):
    notes = []
    mem_dir = Path(mem_dir)
    if not mem_dir.is_dir():
        return notes
    for entry in sorted(os.scandir(str(mem_dir)), key=lambda e: e.name):
        if not entry.name.endswith(".md") or entry.name == "MEMORY.md":
            continue
        try:
            if entry.is_symlink() or not entry.is_file(follow_symlinks=False):
                continue
            info = memory_index.parse_note(entry.path)
        except OSError:
            continue
        info["file"] = entry.name
        notes.append(info)
    return notes


def _one_line(text):
    return " ".join(str(text).split())


def _entry_line(note):
    line = "- [%s](%s)" % (_one_line(note["name"]), quote(note["file"]))
    desc = _one_line(note["description"])
    if desc:
        line += " — " + desc
    if len(line) > MAX_LINE:
        line = line[:MAX_LINE - 1] + "…"
    return line


def _type_rank(type_):
    return (TYPE_ORDER.index(type_), "") if type_ in TYPE_ORDER else (len(TYPE_ORDER), type_)


def _pointer(hidden, suffix=""):
    return "- %d more — use `anthology-mem search`%s" % (hidden, suffix)


def _collapsed_pointer(hidden, suffix=""):
    return "- %d more in other types — use `anthology-mem search`%s" % (hidden, suffix)


def _blen(line):
    return len(line.encode("utf-8")) + 1


def render_index(mem_dir, budget=DEFAULT_BUDGET, suffix="", exclude_types=()):
    """The generated index text for the notes in `mem_dir` (None if there are no notes),
    deterministic (never uses mtimes or the clock). Grouped by type, newest first; over
    budget, entries are shared round-robin across types and each cut type ends with an
    "N more" pointer (with `suffix` appended). If even the headings and pointers of all types
    do not fit, the last types are collapsed into one "N more in other types" pointer.
    Notes whose type is in `exclude_types` are never listed (repo indexes exclude `user`); if
    that leaves none, the text is the generated header alone, so a stale index is replaced."""
    notes = _list_notes(mem_dir)
    if not notes:
        return None
    notes = [n for n in notes if n["type"] not in exclude_types]
    if not notes:
        return GENERATED + "\n"
    notes.sort(key=lambda n: (n["name"], n["file"]))
    by_type = {}
    for n in notes:
        by_type.setdefault(n["type"] or "other", []).append(n)
    groups = []
    for type_ in sorted(by_type, key=_type_rank):
        items = by_type[type_]
        dated = sorted([n for n in items if n["updated"]], key=lambda n: n["updated"], reverse=True)
        undated = [n for n in items if not n["updated"]]
        groups.append((type_, [_entry_line(n) for n in dated + undated]))

    def cost(gi, k):
        type_, entries = groups[gi]
        lines = 1 + k + (1 if k < len(entries) else 0)
        size = _blen("## " + type_) + sum(_blen(e) for e in entries[:k])
        if k < len(entries):
            size += _blen(_pointer(len(entries) - k, suffix))
        return lines, size

    def fits(lines, size):
        return lines <= budget.lines and size <= budget.bytes

    counts = [len(g[1]) for g in groups]
    base_lines, base_bytes = 1, _blen(GENERATED)
    costs = [cost(gi, counts[gi]) for gi in range(len(groups))]
    total_l = base_lines + sum(c[0] for c in costs)
    total_b = base_bytes + sum(c[1] for c in costs)
    collapsed = None
    if not fits(total_l, total_b):
        zero = [cost(gi, 0) for gi in range(len(groups))]
        keep = len(groups)
        while keep > 0:
            hidden = sum(len(g[1]) for g in groups[keep:])
            extra = (1, _blen(_collapsed_pointer(hidden, suffix))) if keep < len(groups) else (0, 0)
            if fits(base_lines + extra[0] + sum(c[0] for c in zero[:keep]),
                    base_bytes + extra[1] + sum(c[1] for c in zero[:keep])):
                break
            keep -= 1
        if keep < len(groups):
            hidden = sum(len(g[1]) for g in groups[keep:])
            collapsed = _collapsed_pointer(hidden, suffix)
            groups = groups[:keep]
            base_lines += 1
            base_bytes += _blen(collapsed)
        counts = [0] * len(groups)
        costs = [cost(gi, 0) for gi in range(len(groups))]
        total_l = base_lines + sum(c[0] for c in costs)
        total_b = base_bytes + sum(c[1] for c in costs)
        live = list(range(len(groups)))
        while live:
            for gi in list(live):
                if counts[gi] >= len(groups[gi][1]):
                    live.remove(gi)
                    continue
                new = cost(gi, counts[gi] + 1)
                nl = total_l - costs[gi][0] + new[0]
                nb = total_b - costs[gi][1] + new[1]
                if not fits(nl, nb):
                    live.remove(gi)
                    continue
                counts[gi] += 1
                costs[gi] = new
                total_l, total_b = nl, nb
    lines = [GENERATED]
    for (type_, entries), k in zip(groups, counts):
        lines.append("## " + type_)
        lines.extend(entries[:k])
        if k < len(entries):
            lines.append(_pointer(len(entries) - k, suffix))
    if collapsed:
        lines.append(collapsed)
    return "\n".join(lines) + "\n"


def regenerate_index(mem_dir, budget=DEFAULT_BUDGET, exclude_types=()):
    """Rewrite `<mem_dir>/MEMORY.md` from the notes' frontmatter (see `render_index`).
    Writes only if the content changed; returns whether it did. A folder without notes is
    left alone."""
    text = render_index(mem_dir, budget, exclude_types=exclude_types)
    if text is None:
        return False
    data = text.encode("utf-8")
    target = Path(mem_dir) / "MEMORY.md"
    try:
        if target.read_bytes() == data:
            return False
    except OSError:
        pass
    _atomic_write(target, data)
    return True


