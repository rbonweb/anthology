def config_dir(env=None):
    """`${CLAUDE_CONFIG_DIR:-~/.claude}`; reads `env` (default: the process environment)."""
    e = os.environ if env is None else env
    base = e.get("CLAUDE_CONFIG_DIR")
    if base:
        return Path(base)
    return Path(e.get("HOME") or os.path.expanduser("~")) / ".claude"


def anthology_home(env=None):
    return config_dir(env) / "anthology"


def _atomic_write(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=".tmp-", suffix=".part")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        os.chmod(tmp, 0o644)
        os.replace(tmp, str(path))
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _git(root, *args, env=None):
    """Run git in `root`; returns the CompletedProcess, or None if git is missing or hangs."""
    e = dict(os.environ)
    if env:
        e.update(env)
    for var in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_COMMON_DIR"):
        e.pop(var, None)
    try:
        return subprocess.run(["git", "-c", "core.fsmonitor=false"] + list(args), cwd=str(root),
                              env=e, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE, timeout=10)
    except (OSError, subprocess.SubprocessError, ValueError):
        return None


def _git_out(root, *args, env=None):
    p = _git(root, *args, env=env)
    if p is None or p.returncode != 0:
        return None
    return p.stdout.decode("utf-8", errors="replace").strip() or None


def repo_root(cwd, env=None):
    """The work tree root (realpath) containing `cwd`, or None when `cwd` is not in a git repo."""
    top = _git_out(cwd, "rev-parse", "--show-toplevel", env=env)
    return Path(os.path.realpath(top)) if top else None


def _main_root(root, env=None):
    """The main work tree's root, so linked worktrees map to the same place as the clone."""
    common = _git_out(root, "rev-parse", "--path-format=absolute", "--git-common-dir", env=env)
    if not common:
        rel = _git_out(root, "rev-parse", "--git-common-dir", env=env)
        common = os.path.join(str(root), rel) if rel else None
    if common and os.path.basename(os.path.normpath(common)) == ".git":
        return Path(os.path.realpath(os.path.dirname(os.path.normpath(common))))
    top = _git_out(root, "rev-parse", "--show-toplevel", env=env)
    return Path(os.path.realpath(top or str(root)))


