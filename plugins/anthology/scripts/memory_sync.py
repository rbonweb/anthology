def sweep_user_notes(src_dir, personal_mem, today=None):
    """Move every `type: user` note out of `src_dir` (repo or agent memory) into
    `personal_mem`: copied with `migrate`'s never-overwrite / side-by-side logic (an identical
    existing copy counts as done); the repo file is deleted only after the personal copy is
    verified byte-identical and the repo file is unchanged. Symlinks, non-regular files and
    symlinked or non-folder folders are never followed or touched. Returns
    `{"moved", "conflicts"}` (file names; a conflict is moved too, kept side by side)."""
    result = {"moved": [], "conflicts": []}
    src = Path(src_dir)
    if src.is_symlink() or not src.is_dir() or _unsafe_dir(personal_mem):
        return result
    date = today or datetime.date.today().isoformat()
    for entry in sorted(os.scandir(str(src)), key=lambda e: e.name):
        if not entry.name.endswith(".md") or entry.name == "MEMORY.md":
            continue
        try:
            if entry.is_symlink() or not entry.is_file(follow_symlinks=False):
                continue
            data = _read_regular(entry.path)
        except (OSError, UnsafeTarget):
            continue
        if note_info(entry.name, data)["type"] != "user":
            continue
        try:
            _ensure_private_dir(personal_mem)
            status, copy = _place(personal_mem, entry.name, data, date)
            if _read_regular(copy) != data or _read_regular(entry.path) != data:
                continue
            os.unlink(entry.path)
        except (OSError, UnsafeTarget):
            continue
        result["moved"].append(entry.name)
        if status == "conflict":
            result["conflicts"].append(entry.name)
    return result


