"""Generate `crates/anthology-shell/src/lexer/pystr_tables.rs`: the CPython `str` predicates the shell parser
uses, so `anthology-shell` (regex and fancy-regex only, design §7.1) matches Python without `anthology-pycompat`.

Usage (repository root, in the pinned Python 3.12 image of ci/images/python.Dockerfile):

    python -I port/extract/shell_unicode.py [--out FILE] [--check]

`--check` exits 1 when the committed file differs from what this interpreter generates.

Every table is read from the running interpreter's behaviour, never from a property name:
- SPACE: `chr(c).isspace()` (str.strip() and str.split() with no argument);
- DIGIT: `chr(c).isdigit()`;
- LOWER: `chr(c).lower()` where it differs from `chr(c)` (full mappings, e.g. U+0130);
- Final_Sigma: CPython lowers U+03A3 to U+03C2 when a cased character precedes it (case-ignorable
  ones skipped) and no cased character follows (case-ignorable ones skipped). For a character X,
  `(X + "Σ").lower()` ends in "ς" exactly when X is cased and not case-ignorable, and
  `("A" + X + "Σ").lower()` ends in "ς" exactly when X is case-ignorable or cased. That gives
  CASE_IGNORABLE and CASED (cased and not case-ignorable: the only cased characters the rule reads).
Surrogates (U+D800..U+DFFF) are not Rust chars and are skipped.
"""
from __future__ import annotations

import argparse
import sys
import unicodedata

OUT = "crates/anthology-shell/src/lexer/pystr_tables.rs"
SIGMA = "Σ"


def code_points():
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        yield c


def ranges(members):
    out = []
    for c in members:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def final(text):
    return text.lower()[-1] == "ς"


def rust_str(s):
    return '"' + "".join(
        ch if 0x20 <= ord(ch) < 0x7F and ch not in '"\\' else "\\u{%x}" % ord(ch) for ch in s) + '"'


def table(name, doc, rs):
    lines = ["/// %s" % doc, "pub(crate) static %s: &[(u32, u32)] = &[" % name]
    for lo, hi in rs:
        lines.append("    (0x%04X, 0x%04X)," % (lo, hi))
    lines.append("];")
    return lines


def generate():
    space, digit, lower, ignorable, cased = [], [], [], [], []
    for c in code_points():
        ch = chr(c)
        if ch.isspace():
            space.append(c)
        if ch.isdigit():
            digit.append(c)
        low = ch.lower()
        if low != ch:
            lower.append((c, low))
        if ch == SIGMA:
            cased.append(c)                       # cased, not case-ignorable
            continue
        alone, after_a = final(ch + SIGMA), final("A" + ch + SIGMA)
        if after_a and not alone:
            ignorable.append(c)
        elif alone:
            cased.append(c)
    lines = [
        "//! Generated by `port/extract/shell_unicode.py` from CPython %s (Unicode %s); do not edit by hand."
        % (sys.version.split()[0], unicodedata.unidata_version),
        "//! Sorted, disjoint, inclusive code point ranges, and the lowercase map, as CPython's `str` sees them.",
        "",
        "/// The Unicode version CPython's tables come from.",
        "#[allow(dead_code)] // read by the tests",
        'pub(crate) const UNICODE_VERSION: &str = "%s";' % unicodedata.unidata_version,
        "",
    ]
    lines += table("SPACE", "`str.isspace()`.", ranges(space)) + [""]
    digits = table("DIGIT", "`str.isdigit()`.", ranges(digit))
    digits.insert(1, "#[allow(dead_code)] // read by the tests")  # unused since fix-wave H
    lines += digits + [""]
    lines += table("CASE_IGNORABLE", "Skipped by CPython's Final_Sigma rule.", ranges(ignorable)) + [""]
    lines += table("CASED", "Cased and not case-ignorable (what the Final_Sigma rule reads).",
                   ranges(cased)) + [""]
    lines.append("/// `chr(c).lower()` for every `c` it changes, sorted by `c`.")
    lines.append("pub(crate) static LOWER: &[(u32, &str)] = &[")
    for c, low in lower:
        lines.append("    (0x%04X, %s)," % (c, rust_str(low)))
    lines.append("];")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = generate()
    if args.check:
        with open(args.out, encoding="utf-8") as f:
            if f.read() != text:
                print("shell_unicode: %s is stale; regenerate it in the 3.12 image" % args.out,
                      file=sys.stderr)
                return 1
        return 0
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
