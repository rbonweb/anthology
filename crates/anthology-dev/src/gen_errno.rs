//! `anthology-dev gen-errno`: pycompat's errno tables (design §12, plan GC-16 I-10). Owner: P1.
//!
//! ```text
//! python3 -I port/difftest/oracle/errno_dump.py > linux.json         # pinned 3.12 image
//! anthology-dev gen-errno < linux.json > crates/anthology-pycompat/src/errno_tables/linux_glibc.rs
//! python3 -I port/difftest/oracle/errno_dump.py > macos.json         # on macOS
//! anthology-dev gen-errno < macos.json > crates/anthology-pycompat/src/errno_tables/macos.rs
//! ```
//!
//! Reads one dump (its format is in `errno_dump.py`) on stdin and writes the table module on
//! stdout, in its `cargo fmt` form. The output depends only on the dump.

use std::ffi::OsString;
use std::io::Read;

use anthology_pycompat::json::{self, Value};

use crate::Output;

/// Runs `anthology-dev gen-errno`; `args` are the arguments after `gen-errno`.
pub fn run(args: &[OsString], stdin: &mut dyn Read) -> Output {
    if !args.is_empty() {
        return Output::usage("gen-errno takes no arguments (the dump is on stdin)");
    }
    let mut text = String::new();
    if let Err(e) = stdin.read_to_string(&mut text) {
        return fail(&format!("cannot read the dump: {e}"));
    }
    match generate(&text) {
        Ok(src) => Output {
            stdout: src.into_bytes(),
            ..Output::default()
        },
        Err(e) => fail(&e),
    }
}

fn fail(msg: &str) -> Output {
    Output {
        stderr: format!("anthology-dev gen-errno: {msg}\n").into_bytes(),
        code: 1,
        ..Output::default()
    }
}

/// The Rust source for a dump.
pub fn generate(dump: &str) -> Result<String, String> {
    let v = json::loads(dump).map_err(|e| format!("the dump is not JSON: {}", e.msg))?;
    let top = v.as_object().ok_or("the dump is not an object")?;
    let os = top.get("os").and_then(Value::as_str).ok_or("no os")?;
    let what = match os {
        "linux" => "glibc Linux (the pinned Python 3.12 image)",
        "macos" => "macOS",
        _ => return Err(format!("unknown os {os:?}")),
    };
    let texts = top.get("text").and_then(Value::as_array).ok_or("no text")?;
    if texts.len() < 2 {
        return Err("the text list is too short".into());
    }
    let unknown = top
        .get("unknown")
        .and_then(Value::as_str)
        .ok_or("no unknown")?;
    let probes = top
        .get("probes")
        .and_then(Value::as_array)
        .ok_or("no probes")?;
    for p in probes {
        let pair = p
            .as_array()
            .filter(|p| p.len() == 2)
            .ok_or("probes: not a pair")?;
        let n = pair[0].as_i64().ok_or("probes: not a number")?;
        let t = pair[1].as_str().ok_or("probes: not a string")?;
        if t != format!("{unknown}{n}") {
            return Err(format!("probe {n} is not in the unknown form: {t:?}"));
        }
    }
    let mut out = format!(
        "//! Generated by `anthology-dev gen-errno` from `port/difftest/oracle/errno_dump.py` on\n\
         //! {what}. Do not edit: regenerate (design §12, plan GC-16 I-10).\n\
         \n\
         /// `os.strerror(n)` for `n` in `0..TEXT.len()` (index `n`).\n\
         pub static TEXT: &[&str] = &[\n"
    );
    for t in texts {
        let t = t.as_str().ok_or("text: not a string")?;
        if t.is_empty() {
            return Err("text: an empty message".into());
        }
        out.push_str(&format!("    {},\n", rust_str(t)));
    }
    out.push_str(&format!(
        "];\n\n/// `os.strerror(n)` of any other `n` is this, then `n` in decimal.\npub const UNKNOWN_PREFIX: &str = {};\n",
        rust_str(unknown)
    ));
    Ok(out)
}

/// A Rust string literal; the texts are printable ASCII in practice, anything else is escaped.
fn rust_str(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' | '\\' => {
                out.push('\\');
                out.push(c);
            }
            ' '..='~' => out.push(c),
            _ => out.push_str(&format!("\\u{{{:x}}}", u32::from(c))),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    const DUMP: &str = r#"{"os": "linux", "probes": [[3, "Unknown error 3"], [-1, "Unknown error -1"]],
        "text": ["Success", "Operation not permitted", "No such \"file\""], "unknown": "Unknown error "}"#;

    #[test]
    fn a_dump_becomes_a_table() {
        let src = generate(DUMP).unwrap();
        assert!(src.contains("glibc Linux"));
        assert!(src.contains(
            "pub static TEXT: &[&str] = &[\n    \"Success\",\n    \"Operation not permitted\",\n    \"No such \\\"file\\\"\",\n];"
        ));
        assert!(src.contains("pub const UNKNOWN_PREFIX: &str = \"Unknown error \";"));
        assert_eq!(src, generate(DUMP).unwrap());
    }

    #[test]
    fn a_bad_dump_is_refused() {
        assert!(generate("{}").is_err());
        let bad_probe = DUMP.replace("[3, \"Unknown error 3\"]", "[3, \"No such process\"]");
        assert!(generate(&bad_probe).unwrap_err().contains("unknown form"));
        let bad_os = DUMP.replace("\"linux\"", "\"windows\"");
        assert!(generate(&bad_os).is_err());
    }

    #[test]
    fn the_command_reads_stdin_and_takes_no_arguments() {
        assert_eq!(run(&[], &mut DUMP.as_bytes()).code, 0);
        assert_eq!(run(&["x".into()], &mut DUMP.as_bytes()).code, 2);
        assert_eq!(run(&[], &mut "[".as_bytes()).code, 1);
    }
}
