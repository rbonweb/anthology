/// The ledger files on disk, by module.
fn ledger_files(root: &Path) -> Result<BTreeMap<String, PathBuf>, String> {
    let dir = root.join(LEDGER_DIR);
    let mut out = BTreeMap::new();
    let entries = match fs::read_dir(&dir) {
        Ok(e) => e,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(out),
        Err(e) => return Err(format!("cannot read {}: {e}", dir.display())),
    };
    for entry in entries {
        let entry = entry.map_err(|e| format!("cannot read {}: {e}", dir.display()))?;
        let name = entry.file_name().to_string_lossy().into_owned();
        if let Some(module) = name.strip_suffix(".tsv")
            && format!("{LEDGER_DIR}/{name}") != EXCEPTIONS_FILE
        {
            out.insert(module.to_string(), entry.path());
        }
    }
    Ok(out)
}

/// Difftest surface names (`pub const NAME: &str = "…";` in `crates/difftest/src/surfaces/`).
fn surface_names(root: &Path) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let dir = root.join("crates/difftest/src/surfaces");
    let Ok(entries) = fs::read_dir(dir) else {
        return out;
    };
    for entry in entries.flatten() {
        let Ok(text) = fs::read_to_string(entry.path()) else {
            continue;
        };
        for line in text.lines() {
            if let Some(rest) = line.trim().strip_prefix("pub const NAME: &str = \"")
                && let Some(name) = rest.strip_suffix("\";")
            {
                out.insert(name.to_string());
            }
        }
    }
    out
}

/// The `crates/<crate>/<sub>/<name>` paths that exist, for every crate.
fn crate_files(root: &Path, sub: &str, name: &str) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let Ok(entries) = fs::read_dir(root.join("crates")) else {
        return out;
    };
    let mut dirs: Vec<PathBuf> = entries.flatten().map(|e| e.path()).collect();
    dirs.sort();
    for dir in dirs {
        let path = dir.join(sub).join(name);
        if path.is_file() {
            out.push(path);
        }
    }
    out
}

/// The value after the first `"<key>":` of `line` (leading blanks skipped).
fn json_value_after<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    let quoted = format!("\"{key}\"");
    let at = line.find(&quoted)?;
    let rest = line[at + quoted.len()..].trim_start().strip_prefix(':')?;
    Some(rest.trim_start())
}

/// Rust rows of `crates/<crate_dir>/tests/data/<module>.jsonl`: per `"py"` id, the distinct
/// `"row"` indices (the first `"py": "<id>"` and the first `"row": <n>` of each line).
fn rust_rows(root: &Path, crate_dir: &str, module: &str) -> HashMap<String, BTreeSet<u64>> {
    let mut out: HashMap<String, BTreeSet<u64>> = HashMap::new();
    let path = root
        .join("crates")
        .join(crate_dir)
        .join("tests/data")
        .join(format!("{module}.jsonl"));
    let Ok(text) = fs::read_to_string(&path) else {
        return out;
    };
    for line in text.lines() {
        let Some(id) = json_value_after(line, "py")
            .and_then(|v| v.strip_prefix('"'))
            .and_then(|v| v.split_once('"'))
            .map(|(id, _)| id)
        else {
            continue;
        };
        let Some(row) = json_value_after(line, "row").and_then(|v| {
            let digits: String = v.chars().take_while(char::is_ascii_digit).collect();
            digits.parse::<u64>().ok()
        }) else {
            continue;
        };
        out.entry(id.to_string()).or_default().insert(row);
    }
    out
}

