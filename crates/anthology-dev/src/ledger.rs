/// Rewrites one module's ledger: rows in id order, a `todo` row for each new id, stale `todo`
/// rows removed, stale rows with any other status kept at the end (and reported).
pub fn sync_ledger(module: &str, existing: &str, ids: &[&str], stale: &mut Vec<String>) -> String {
    let mut problems = Vec::new();
    let rows = parse_ledger(existing, module, &mut problems);
    // Every row of an id (a repeated id keeps all its rows, for `check` to report).
    let mut by_id: HashMap<&str, Vec<&Row>> = HashMap::new();
    for row in &rows {
        by_id.entry(row.id.as_str()).or_default().push(row);
    }
    let wanted: BTreeSet<&str> = ids.iter().copied().collect();
    let mut out = String::new();
    // Keep the existing comment block, or write the header.
    let comments: Vec<&str> = existing
        .lines()
        .take_while(|l| l.starts_with('#'))
        .collect();
    if comments.is_empty() {
        out.push_str(LEDGER_HEADER);
    } else {
        for c in comments {
            out.push_str(c);
            out.push('\n');
        }
    }
    for id in ids {
        match by_id.get(id) {
            Some(found) => {
                for row in found {
                    out.push_str(&row.raw);
                    out.push('\n');
                }
            }
            None => {
                out.push_str(id);
                out.push_str("\ttodo\n");
            }
        }
    }
    for row in &rows {
        if !wanted.contains(row.id.as_str()) && !matches!(row.status, Status::Todo(_)) {
            stale.push(format!("{module}: {} ({})", row.id, row.status.label()));
            out.push_str(&row.raw);
            out.push('\n');
        }
    }
    // Lines that did not parse are kept, so nothing a person wrote is lost.
    for (_, line) in data_lines(existing) {
        if !rows.iter().any(|r| r.raw == line) {
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

/// `ledger ids`: without `--fresh`, the committed id count per module; with it, the differences;
/// with `--write`, the fresh files are committed and the ledgers synced.
pub fn ids(args: &IdsArgs) -> Output {
    let root = args.root.as_path();
    let Some(fresh) = &args.fresh else {
        let mut problems = Vec::new();
        let text = match read(&root.join(IDS_FILE)) {
            Ok(t) => t,
            Err(e) => return fail(&e),
        };
        let ids = parse_ids(&text, IDS_FILE, &mut problems);
        if !problems.is_empty() {
            return fail(&problems.join("\n"));
        }
        let mut per: BTreeMap<&str, usize> = BTreeMap::new();
        for id in &ids {
            *per.entry(module_of(id)).or_insert(0) += 1;
        }
        let mut out = String::new();
        for (module, n) in &per {
            let _ = writeln!(out, "{module:<28} {n:>5}");
        }
        let _ = writeln!(out, "{:<28} {:>5}", "total", ids.len());
        return Output {
            stdout: out.into_bytes(),
            ..Output::default()
        };
    };
    if !args.write {
        let mut problems = Vec::new();
        check_fresh(root, fresh, &mut problems);
        return if problems.is_empty() {
            Output {
                stdout:
                    b"ledger: the committed id list, row counts and regex inventory are current\n"
                        .to_vec(),
                ..Output::default()
            }
        } else {
            fail(&problems.join("\nanthology-dev ledger: "))
        };
    }
    match write_fresh(root, fresh) {
        Ok(report) => Output {
            stdout: report.into_bytes(),
            ..Output::default()
        },
        Err(e) => fail(&e),
    }
}

fn write_fresh(root: &Path, fresh: &Path) -> Result<String, String> {
    // Validate the fresh files before anything is written.
    let mut problems = Vec::new();
    let ids_text = read(&fresh.join(FRESH_IDS))?;
    let rows_text = read(&fresh.join(FRESH_ROWS))?;
    let inventory_text = read(&fresh.join(FRESH_INVENTORY))?;
    let ids = parse_ids(&ids_text, FRESH_IDS, &mut problems);
    parse_rows(&rows_text, FRESH_ROWS, &mut problems);
    parse_inventory(&inventory_text, FRESH_INVENTORY, &mut problems);
    if ids.is_empty() {
        problems.push(format!("{FRESH_IDS}: no ids"));
    }
    if !problems.is_empty() {
        return Err(problems.join("\n"));
    }
    let write = |rel: &str, text: &str| -> Result<(), String> {
        let path = root.join(rel);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .map_err(|e| format!("cannot create {}: {e}", parent.display()))?;
        }
        fs::write(&path, text).map_err(|e| format!("cannot write {}: {e}", path.display()))
    };
    write(IDS_FILE, &ids_text)?;
    write(ROWS_FILE, &rows_text)?;
    write(INVENTORY_FILE, &inventory_text)?;

    let mut by_module: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for id in &ids {
        by_module.entry(module_of(id)).or_default().push(id);
    }
    let files = ledger_files(root)?;
    let mut stale = Vec::new();
    let mut created = 0;
    for (module, module_ids) in &by_module {
        let existing = match files.get(*module) {
            Some(path) => read(path)?,
            None => {
                created += 1;
                String::new()
            }
        };
        let text = sync_ledger(module, &existing, module_ids, &mut stale);
        write(&format!("{LEDGER_DIR}/{module}.tsv"), &text)?;
    }
    for (module, path) in &files {
        if !by_module.contains_key(module.as_str()) {
            let mut problems = Vec::new();
            let rows = parse_ledger(&read(path)?, module, &mut problems);
            if rows.iter().all(|r| matches!(r.status, Status::Todo(_))) && problems.is_empty() {
                fs::remove_file(path)
                    .map_err(|e| format!("cannot remove {}: {e}", path.display()))?;
            } else {
                stale.push(format!(
                    "{module}: the module is gone; resolve its rows by hand"
                ));
            }
        }
    }
    let mut out = format!(
        "ledger: wrote {} ids in {} modules ({created} new ledger files)\n",
        ids.len(),
        by_module.len()
    );
    for s in &stale {
        let _ = writeln!(out, "ledger: stale row kept for review: {s}");
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn statuses_parse() {
        assert_eq!(Status::parse("ported"), Ok(Status::Ported));
        assert_eq!(Status::parse("todo"), Ok(Status::Todo(None)));
        assert_eq!(
            Status::parse("todo:MS2"),
            Ok(Status::Todo(Some("MS2".into())))
        );
        assert_eq!(
            Status::parse("todo:RT1a"),
            Ok(Status::Todo(Some("RT1a".into())))
        );
        assert!(Status::parse("todo:ms2").is_err());
        assert!(Status::parse("todo:ZZ9").is_err(), "not a task of plan §4");
        assert!(Status::parse("todo:").is_err());
        assert_eq!(
            Status::parse("merged:test_a.A.test_b"),
            Ok(Status::Merged("test_a.A.test_b".into()))
        );
        assert!(Status::parse("merged:test_b").is_err());
        assert_eq!(
            Status::parse("golden:guard.check"),
            Ok(Status::Golden("guard.check".into()))
        );
        assert!(Status::parse("golden:").is_err());
        for ok in [
            "py-compat",
            "python-runtime",
            "superseded:F-1",
            "superseded:F-20",
        ] {
            assert_eq!(
                Status::parse(&format!("dropped:{ok}")),
                Ok(Status::Dropped(ok.into())),
                "{ok}"
            );
        }
        for bad in [
            "superseded:F-0",
            "superseded:F-21",
            "superseded:F-07",
            "other",
            "",
        ] {
            assert!(Status::parse(&format!("dropped:{bad}")).is_err(), "{bad}");
        }
        assert!(Status::parse("done").is_err());
    }

    #[test]
    fn ids_must_be_sorted_unique_and_well_formed() {
        let mut problems = Vec::new();
        let ids = parse_ids("# c\nt.A.test_a\nt.A.test_b\n", "x", &mut problems);
        assert_eq!(ids.len(), 2);
        assert!(problems.is_empty());
        parse_ids(
            "t.A.test_b\nt.A.test_a\nt.A.test_a\nnot-an-id\n",
            "x",
            &mut problems,
        );
        assert_eq!(problems.len(), 3, "{problems:?}");
    }

    #[test]
    fn module_args() {
        assert_eq!(module_arg("tests/test_x.py").as_deref(), Ok("test_x"));
        assert_eq!(module_arg("test_x.py").as_deref(), Ok("test_x"));
        assert_eq!(module_arg("test_x").as_deref(), Ok("test_x"));
        assert!(module_arg("tests/").is_err());
        assert!(module_arg("a-b.py").is_err());
    }

    #[test]
    fn sync_adds_todo_rows_keeps_decisions_and_drops_stale_todos() {
        let existing = "# python_id\tstatus\trust_test\tnote\n\
                        m.A.test_b\tported\tcrates/x/tests/m.rs::test_b\n\
                        m.A.test_old\ttodo\n\
                        m.A.test_gone\tdropped:py-compat\t\tno Rust\n";
        let mut stale = Vec::new();
        let text = sync_ledger("m", existing, &["m.A.test_a", "m.A.test_b"], &mut stale);
        assert_eq!(
            text,
            "# python_id\tstatus\trust_test\tnote\n\
             m.A.test_a\ttodo\n\
             m.A.test_b\tported\tcrates/x/tests/m.rs::test_b\n\
             m.A.test_gone\tdropped:py-compat\t\tno Rust\n"
        );
        assert_eq!(stale, vec!["m: m.A.test_gone (dropped)".to_string()]);
        let repeated = "m.A.test_a\tported\tcrates/x/tests/m.rs::test_a\nm.A.test_a\ttodo\n";
        let mut stale = Vec::new();
        assert_eq!(
            sync_ledger("m", repeated, &["m.A.test_a"], &mut stale),
            format!("{LEDGER_HEADER}{repeated}"),
            "a repeated id keeps every row"
        );
        let mut none = Vec::new();
        assert_eq!(
            sync_ledger("m", "", &["m.A.test_a"], &mut none),
            format!("{LEDGER_HEADER}m.A.test_a\ttodo\n")
        );
    }
}
