#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Status {
    Ported,
    Merged(String),
    Golden(String),
    Dropped(String),
    /// `todo`, or `todo:<TASK>`.
    Todo(Option<String>),
}

impl Status {
    pub fn parse(s: &str) -> Result<Status, String> {
        if s == "ported" {
            return Ok(Status::Ported);
        }
        if s == "todo" {
            return Ok(Status::Todo(None));
        }
        if let Some(task) = s.strip_prefix("todo:") {
            return if is_task(task) {
                Ok(Status::Todo(Some(task.to_string())))
            } else {
                Err(format!(
                    "`todo:` needs a task id (MS2, RT1a, …), not {task:?}"
                ))
            };
        }
        if let Some(id) = s.strip_prefix("merged:") {
            return if is_python_id(id) {
                Ok(Status::Merged(id.to_string()))
            } else {
                Err(format!("`merged:` needs a Python test id, not {id:?}"))
            };
        }
        if let Some(corpus) = s.strip_prefix("golden:") {
            let ok = !corpus.is_empty()
                && corpus
                    .chars()
                    .all(|c| c.is_ascii_alphanumeric() || "._-".contains(c));
            return if ok {
                Ok(Status::Golden(corpus.to_string()))
            } else {
                Err(format!("`golden:` needs a corpus name, not {corpus:?}"))
            };
        }
        if let Some(reason) = s.strip_prefix("dropped:") {
            // F-1 to F-20 exactly, written without a leading zero.
            let superseded = reason.strip_prefix("superseded:F-").is_some_and(|n| {
                matches!(n.parse::<u32>(), Ok(v) if (1..=20).contains(&v) && v.to_string() == n)
            });
            return if matches!(reason, "py-compat" | "python-runtime") || superseded {
                Ok(Status::Dropped(reason.to_string()))
            } else {
                Err(format!(
                    "unknown drop reason {reason:?} (py-compat, python-runtime, superseded:F-1..20)"
                ))
            };
        }
        Err(format!(
            "unknown status {s:?} (ported, merged:<id>, golden:<corpus>, dropped:<reason>, todo)"
        ))
    }

    fn label(&self) -> &'static str {
        match self {
            Status::Ported => "ported",
            Status::Merged(_) => "merged",
            Status::Golden(_) => "golden",
            Status::Dropped(_) => "dropped",
            Status::Todo(None) => "todo",
            Status::Todo(Some(_)) => "deferred",
        }
    }
}

#[derive(Debug, Clone)]
pub struct Row {
    pub id: String,
    pub status: Status,
    pub rust_test: String,
    pub note: String,
    pub line: usize,
    pub raw: String,
}

/// One `port/ledger/<module>.tsv`. Malformed lines become problems.
pub fn parse_ledger(text: &str, what: &str, problems: &mut Vec<String>) -> Vec<Row> {
    let mut rows = Vec::new();
    for (n, line) in data_lines(text) {
        let fields: Vec<&str> = line.split('\t').collect();
        if !(2..=4).contains(&fields.len()) {
            problems.push(format!(
                "{what}:{n}: not `python_id<TAB>status[<TAB>rust_test[<TAB>note]]`: {line:?}"
            ));
            continue;
        }
        let id = fields[0];
        if !is_python_id(id) {
            problems.push(format!("{what}:{n}: not a Python test id: {id:?}"));
            continue;
        }
        match Status::parse(fields[1]) {
            Ok(status) => rows.push(Row {
                id: id.to_string(),
                status,
                rust_test: fields.get(2).copied().unwrap_or("").to_string(),
                note: fields.get(3).copied().unwrap_or("").to_string(),
                line: n,
                raw: line.to_string(),
            }),
            Err(e) => problems.push(format!("{what}:{n}: {id}: {e}")),
        }
    }
    rows
}

