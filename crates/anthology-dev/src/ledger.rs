/// What `check` found: the problems that fail it, and the informational lines.
#[derive(Debug, Default)]
pub struct Findings {
    pub problems: Vec<String>,
    pub notes: Vec<String>,
    pub summary: Vec<(String, BTreeMap<&'static str, usize>)>,
    /// `--report` lists: rows deferred to a task, and rows whose count is `rows:computed`.
    pub deferred: Vec<String>,
    pub computed: Vec<String>,
    /// `--report` list: every `merged:` row, with its note.
    pub merged: Vec<String>,
}

fn compare_sets(
    what: &str,
    committed: &BTreeSet<String>,
    fresh: &BTreeSet<String>,
    added: &str,
    removed: &str,
    problems: &mut Vec<String>,
) {
    const SHOW: usize = 25;
    let new: Vec<&String> = fresh.difference(committed).collect();
    let gone: Vec<&String> = committed.difference(fresh).collect();
    for (list, label) in [(&new, added), (&gone, removed)] {
        for item in list.iter().take(SHOW) {
            problems.push(format!("{what}: {label}: {item}"));
        }
        if list.len() > SHOW {
            problems.push(format!("{what}: … and {} more {label}", list.len() - SHOW));
        }
    }
}

/// Compares a fresh extraction with the committed files.
fn check_fresh(root: &Path, fresh: &Path, problems: &mut Vec<String>) {
    let regenerate = "regenerate with `ci/jobs/ledger.sh --write`";
    let pairs = [
        (FRESH_IDS, IDS_FILE),
        (FRESH_ROWS, ROWS_FILE),
        (FRESH_INVENTORY, INVENTORY_FILE),
    ];
    for (fresh_name, committed_name) in pairs {
        let fresh_text = match read(&fresh.join(fresh_name)) {
            Ok(t) => t,
            Err(e) => {
                problems.push(format!("fresh extraction: {e}"));
                continue;
            }
        };
        let committed_text = read(&root.join(committed_name)).unwrap_or_default();
        let mut ignored = Vec::new();
        let (committed, fresh): (BTreeSet<String>, BTreeSet<String>) = match fresh_name {
            FRESH_IDS => (
                parse_ids(&committed_text, committed_name, &mut ignored)
                    .into_iter()
                    .collect(),
                parse_ids(&fresh_text, fresh_name, problems)
                    .into_iter()
                    .collect(),
            ),
            FRESH_ROWS => (
                parse_rows(&committed_text, committed_name, &mut ignored)
                    .into_iter()
                    .map(|(k, v)| format!("{k} ({v} rows)"))
                    .collect(),
                parse_rows(&fresh_text, fresh_name, problems)
                    .into_iter()
                    .map(|(k, v)| format!("{k} ({v} rows)"))
                    .collect(),
            ),
            _ => (
                parse_inventory(&committed_text, committed_name, &mut ignored),
                parse_inventory(&fresh_text, fresh_name, problems),
            ),
        };
        let before = problems.len();
        let (added, removed) = match fresh_name {
            FRESH_IDS => (
                "Python test not in the id list",
                "id no longer run by Python",
            ),
            FRESH_ROWS => ("row count not committed", "committed row count is stale"),
            _ => (
                "lookaround or backreference pattern not in the inventory",
                "inventory row no longer in the Python",
            ),
        };
        compare_sets(committed_name, &committed, &fresh, added, removed, problems);
        if problems.len() > before {
            problems.push(format!("{committed_name}: out of date; {regenerate}"));
        }
    }
}

/// Runs every check; `files`/`task`/`report` decide which `todo` rows fail.
pub fn findings(args: &CheckArgs) -> Result<Findings, String> {
    let root = args.root.as_path();
    if !root.join("port").is_dir() {
        return Err(format!(
            "{} has no port/ directory (run from the repository root or give --root)",
            root.display()
        ));
    }
    let mut out = Findings::default();
    let problems = &mut out.problems;

    // The committed id, row and inventory files.
    let ids = parse_ids(&read(&root.join(IDS_FILE))?, IDS_FILE, problems);
    let id_set: BTreeSet<&str> = ids.iter().map(String::as_str).collect();
    let rows = match fs::read_to_string(root.join(ROWS_FILE)) {
        Ok(t) => parse_rows(&t, ROWS_FILE, problems),
        Err(e) => {
            problems.push(format!("cannot read {ROWS_FILE}: {e}"));
            BTreeMap::new()
        }
    };
    for id in rows.keys() {
        if !id_set.contains(id.as_str()) {
            problems.push(format!("{ROWS_FILE}: {id} is not in {IDS_FILE}"));
        }
    }
    match fs::read_to_string(root.join(INVENTORY_FILE)) {
        Ok(t) => {
            parse_inventory(&t, INVENTORY_FILE, problems);
        }
        Err(e) => problems.push(format!("cannot read {INVENTORY_FILE}: {e}")),
    }
    let platform = args.platform.clone().unwrap_or_default();
    let listing = match (&args.fresh, &args.listings) {
        (Some(fresh), _) => {
            check_fresh(root, fresh, problems);
            Some(load_listings(fresh, &platform, problems))
        }
        (None, Some(dir)) => {
            out.notes.push(format!(
                "--listings: the {platform} cargo listings are checked; {IDS_FILE}, {ROWS_FILE} \
                 and {INVENTORY_FILE} are taken as current (ci/jobs/ledger.sh compares them)"
            ));
            Some(load_listings(dir, &platform, problems))
        }
        (None, None) => {
            out.notes.push(format!(
                "--no-fresh: {IDS_FILE}, {ROWS_FILE} and {INVENTORY_FILE} are taken as current, \
                 and Rust targets are checked statically only (no `cargo test -- --list`); \
                 ci/jobs/ledger.sh and rust-test-macos check both"
            ));
            None
        }
    };

    // Modules: from the id list, and the files on disk.
    let mut by_module: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for id in &ids {
        by_module.entry(module_of(id)).or_default().push(id);
    }
    for module in &args.files {
        if !by_module.contains_key(module.as_str()) {
            return Err(format!(
                "--files {module}: no ids of that module in {IDS_FILE}"
            ));
        }
        if let Some(task) = &args.task
            && !owners_of(module).contains(&task.as_str())
        {
            return Err(format!(
                "--task {task} does not own {module} (plan §5 owners: {})",
                owners_of(module).join(", ")
            ));
        }
    }
    let files = ledger_files(root)?;
    for module in files.keys() {
        if !by_module.contains_key(module.as_str()) {
            problems.push(format!(
                "{LEDGER_DIR}/{module}.tsv: no ids of module {module} in {IDS_FILE} (stale file)"
            ));
        }
    }

    // Every row, and the status of every id.
    let mut all_rows: BTreeMap<String, Row> = BTreeMap::new();
    let mut module_rows: BTreeMap<&str, Vec<Row>> = BTreeMap::new();
    for module in by_module.keys() {
        let what = format!("{LEDGER_DIR}/{module}.tsv");
        let Some(path) = files.get(*module) else {
            problems.push(format!(
                "{what}: missing (every id of {module} needs a row)"
            ));
            module_rows.insert(module, Vec::new());
            continue;
        };
        let parsed = parse_ledger(&read(path)?, &what, problems);
        let mut kept = Vec::new();
        for row in parsed {
            if module_of(&row.id) != *module {
                problems.push(format!(
                    "{what}:{}: {} belongs in {LEDGER_DIR}/{}.tsv",
                    row.line,
                    row.id,
                    module_of(&row.id)
                ));
            } else if !id_set.contains(row.id.as_str()) {
                problems.push(format!(
                    "{what}:{}: {} is not in {IDS_FILE} (a stale row)",
                    row.line, row.id
                ));
            } else if all_rows.contains_key(&row.id) {
                problems.push(format!("{what}:{}: {} is repeated", row.line, row.id));
            } else {
                all_rows.insert(row.id.clone(), row.clone());
                kept.push(row);
            }
        }
        module_rows.insert(module, kept);
    }

    // Which modules' `todo` rows fail.
    let claimed: BTreeSet<&str> = module_rows
        .iter()
        .filter(|(_, rows)| rows.iter().any(|r| !matches!(r.status, Status::Todo(_))))
        .map(|(m, _)| *m)
        .collect();
    let full = args.files.is_empty() && !args.report;
    let strict = |module: &str| {
        full || args.files.iter().any(|f| f == module) || (args.report && claimed.contains(module))
    };

    let surfaces = surface_names(root);
    let exceptions = parse_exceptions(root, &id_set, problems);
    let mut scanned = targets::ScanCache::new();
    // Each `ported` target is claimed once (many-to-one coverage is `merged:`).
    let mut claims: BTreeMap<&str, &str> = BTreeMap::new();
    for row in all_rows.values() {
        if row.status == Status::Ported && !row.rust_test.is_empty() {
            if let Some(first) = claims.get(row.rust_test.as_str()) {
                problems.push(format!(
                    "{LEDGER_DIR}/{}.tsv:{}: {}: rust_test {} is already the port of {first}; \
                     one Rust test per ported row (mark the other `merged:{first}`)",
                    module_of(&row.id),
                    row.line,
                    row.id,
                    row.rust_test
                ));
            } else {
                claims.insert(&row.rust_test, &row.id);
            }
        }
    }
    for (module, ids_of_module) in &by_module {
        let what = format!("{LEDGER_DIR}/{module}.tsv");
        let rows_here = &module_rows[module];
        let mut counts: BTreeMap<&'static str, usize> = BTreeMap::new();
        let have: BTreeSet<&str> = rows_here.iter().map(|r| r.id.as_str()).collect();
        if files.contains_key(*module) {
            for id in ids_of_module {
                if !have.contains(id) {
                    problems.push(format!("{what}: {id}: missing row"));
                }
            }
        }
        let mut rust_by_crate: HashMap<String, HashMap<String, BTreeSet<u64>>> = HashMap::new();
        for row in rows_here {
            let at = format!("{what}:{}: {}", row.line, row.id);
            *counts.entry(row.status.label()).or_insert(0) += 1;
            if !matches!(row.status, Status::Ported) && !row.rust_test.is_empty() {
                problems.push(format!(
                    "{at}: only a ported row names a rust_test (put it in the note)"
                ));
            }
            match &row.status {
                Status::Ported => {
                    let method = method_of(&row.id);
                    let listed = listing.as_ref();
                    let only_on = match platform_note(&row.note) {
                        Ok(None) => None,
                        Ok(Some(p)) => {
                            if !exceptions.contains(&(row.id.clone(), p.to_string())) {
                                problems.push(format!(
                                    "{at}: `platform:{p}` needs the pair ({}, {p}) in \
                                     {EXCEPTIONS_FILE}, which the controller owns",
                                    row.id
                                ));
                            }
                            Some(p)
                        }
                        Err(e) => {
                            problems.push(format!("{at}: {e}"));
                            None
                        }
                    };
                    if let Some(p) =
                        targets::check(root, &row.rust_test, method, listed, only_on, &mut scanned)
                    {
                        problems.push(format!("{at}: {p}"));
                    }
                }
                Status::Merged(target) => {
                    out.merged
                        .push(format!("{}\tmerged:{target}\t{}", row.id, row.note));
                    let problem = match all_rows.get(target) {
                        _ if module_of(target) != *module => {
                            Some("which is in another module (merge within the module)")
                        }
                        Some(t) if t.status == Status::Ported => None,
                        Some(_) => Some("which is not ported (merge into a ported test)"),
                        None => Some("which has no row"),
                    };
                    if let Some(p) = problem {
                        problems.push(format!("{at}: merged into {target}, {p}"));
                    }
                    if row.note.trim().is_empty() {
                        problems.push(format!(
                            "{at}: a merged row needs a note (how {target}'s Rust test covers it)"
                        ));
                    }
                    if !matches!(platform_note(&row.note), Ok(None)) {
                        problems.push(format!(
                            "{at}: a merged row cannot carry a `platform:` note (port it on its own)"
                        ));
                    }
                    if let Some(t) = all_rows.get(target)
                        && !matches!(platform_note(&t.note), Ok(None))
                    {
                        problems.push(format!(
                            "{at}: merged into {target}, whose Rust test runs on one platform only \
                             (`platform:`); port this test on its own"
                        ));
                    }
                }
                Status::Golden(corpus) => {
                    let file = format!("{corpus}.jsonl");
                    if !surfaces.contains(corpus)
                        && crate_files(root, "tests/golden", &file).is_empty()
                    {
                        problems.push(format!(
                            "{at}: golden corpus {corpus} is neither a difftest surface nor \
                             crates/*/tests/golden/{file}"
                        ));
                    }
                }
                Status::Dropped(_) => {
                    if row.note.trim().is_empty() {
                        problems.push(format!(
                            "{at}: a dropped row needs a note (its replacement test, if any)"
                        ));
                    }
                }
                Status::Todo(None) => {
                    if strict(module) {
                        problems.push(format!("{at}: still todo"));
                    }
                }
                Status::Todo(Some(task)) => {
                    out.deferred.push(format!("{}\ttodo:{task}", row.id));
                    if !owners_of(module).contains(&task.as_str()) {
                        problems.push(format!(
                            "{at}: deferred to {task}, which does not own {module} (plan §5 \
                             owners: {})",
                            owners_of(module).join(", ")
                        ));
                    }
                    let in_files = args.files.iter().any(|f| f == module);
                    if full || (in_files && args.task.as_deref() == Some(task.as_str())) {
                        problems.push(format!("{at}: still todo (deferred to {task})"));
                    } else if in_files && args.task.is_none() {
                        problems.push(format!(
                            "{at}: deferred to {task}; a --files check of a module with deferred \
                             rows needs --task <the task being checked>"
                        ));
                    }
                }
            }
            let needs_rows = matches!(row.status, Status::Ported | Status::Merged(_));
            let Some(&want) = rows.get(&row.id).filter(|_| needs_rows) else {
                continue;
            };
            if let Some(reason) = computed_reason(&row.note) {
                *counts.entry("computed").or_insert(0) += 1;
                if reason.is_empty() {
                    problems.push(format!(
                        "{at}: `{ROWS_COMPUTED}` needs a reason after it (how the Rust test gets \
                         the {want} rows)"
                    ));
                }
                out.computed
                    .push(format!("{}\t{want} rows\t{}", row.id, row.note));
                continue;
            }
            // The crate whose data file holds the rows: the row's own target, or its merge
            // target's.
            let target = match &row.status {
                Status::Merged(t) => all_rows.get(t).map_or("", |r| r.rust_test.as_str()),
                _ => row.rust_test.as_str(),
            };
            let Some(crate_dir) = targets::crate_dir_of(target) else {
                continue; // the target itself is reported above
            };
            let rust = rust_by_crate
                .entry(crate_dir.to_string())
                .or_insert_with(|| rust_rows(root, crate_dir, module));
            let have = rust.get(&row.id);
            let got = have.map_or(0, BTreeSet::len);
            let complete = (0..want).all(|n| have.is_some_and(|h| h.contains(&n)));
            if !complete {
                problems.push(format!(
                    "{at}: {got} distinct Rust rows tagged \"py\" in \
                     crates/{crate_dir}/tests/data/{module}.jsonl, but the Python test has {want} \
                     (rows \"row\": 0..{want} needed, or note `{ROWS_COMPUTED} <reason>`)"
                ));
            }
        }
        counts.insert("ids", ids_of_module.len());
        out.summary.push((module.to_string(), counts));
    }
    Ok(out)
}

/// The four listing files of `dir` (one platform's `cargo test -- --list [--ignored]`, plain and
/// `--all-features`).
fn load_listings(dir: &Path, platform: &str, problems: &mut Vec<String>) -> targets::Listings {
    let mut l = targets::Listings {
        platform: platform.to_string(),
        ..targets::Listings::default()
    };
    for (name, ignored) in [
        (FRESH_LIST_PLAIN, false),
        (FRESH_LIST_ALL, false),
        (FRESH_LIST_IGNORED_PLAIN, true),
        (FRESH_LIST_IGNORED_ALL, true),
    ] {
        match read(&dir.join(name)) {
            Ok(text) if ignored => l.ignored.add(&text),
            Ok(text) => l.listed.add(&text),
            Err(e) => problems.push(format!("{platform} listings: {e}")),
        }
    }
    if l.listed.is_empty() {
        problems.push(format!(
            "{platform} listings: no tests in {FRESH_LIST_PLAIN} or {FRESH_LIST_ALL} \
             (`cargo test --workspace --locked -- --list` output)"
        ));
    }
    l
}

/// `port/ledger/platform-exceptions.tsv`: `python_id<TAB>platform<TAB>reason` rows (a missing
/// file is an empty table).
fn parse_exceptions(
    root: &Path,
    ids: &BTreeSet<&str>,
    problems: &mut Vec<String>,
) -> BTreeSet<(String, String)> {
    let mut out = BTreeSet::new();
    let Ok(text) = fs::read_to_string(root.join(EXCEPTIONS_FILE)) else {
        return out;
    };
    for (n, line) in data_lines(&text) {
        let fields: Vec<&str> = line.split('\t').collect();
        let at = format!("{EXCEPTIONS_FILE}:{n}");
        let [id, platform, reason] = fields[..] else {
            problems.push(format!(
                "{at}: not `python_id<TAB>platform<TAB>reason`: {line:?}"
            ));
            continue;
        };
        if !ids.contains(id) {
            problems.push(format!("{at}: {id} is not in {IDS_FILE}"));
        } else if !targets::PLATFORMS.contains(&platform) {
            problems.push(format!("{at}: {platform} is not linux or macos"));
        } else if reason.trim().is_empty() {
            problems.push(format!("{at}: an exception needs a reason"));
        } else if !out.insert((id.to_string(), platform.to_string())) {
            problems.push(format!("{at}: repeated"));
        }
    }
    out
}

/// The `platform:<linux|macos>` token of a ported row's note: the Rust test runs on that
/// platform only.
fn platform_note(note: &str) -> Result<Option<&'static str>, String> {
    let mut found = None;
    for word in note.split_whitespace() {
        let word = word.trim_end_matches([',', ';', '.', ')']);
        if let Some(p) = word.strip_prefix("platform:") {
            let Some(known) = targets::PLATFORMS.iter().find(|k| **k == p) else {
                return Err(format!(
                    "`platform:{p}` is not platform:linux or platform:macos"
                ));
            };
            if found.replace(*known).is_some() {
                return Err("more than one `platform:` in the note".into());
            }
        }
    }
    Ok(found)
}

/// The reason after `rows:computed` in `note`, if the token is there.
fn computed_reason(note: &str) -> Option<&str> {
    let at = note.find(ROWS_COMPUTED)?;
    Some(note[at + ROWS_COMPUTED.len()..].trim())
}

fn render_summary(summary: &[(String, BTreeMap<&'static str, usize>)]) -> String {
    let columns = [
        "ids", "ported", "merged", "golden", "dropped", "deferred", "todo", "computed",
    ];
    let mut out = format!("{:<28}", "module");
    for c in columns {
        let _ = write!(out, " {c:>8}");
    }
    out.push('\n');
    let mut totals = [0usize; 8];
    for (module, counts) in summary {
        let _ = write!(out, "{module:<28}");
        for (i, c) in columns.iter().enumerate() {
            let n = counts.get(c).copied().unwrap_or(0);
            totals[i] += n;
            let _ = write!(out, " {n:>8}");
        }
        out.push('\n');
    }
    let _ = write!(out, "{:<28}", "total");
    for n in totals {
        let _ = write!(out, " {n:>8}");
    }
    out.push('\n');
    out
}

/// `ledger check`: exit 0 when nothing fails, 1 with every problem listed, 2 on usage errors.
pub fn check(args: &CheckArgs) -> Output {
    let found = match findings(args) {
        Ok(f) => f,
        Err(e) => return fail(&e),
    };
    let mut stdout = String::new();
    let mut stderr = String::new();
    if args.report {
        stdout.push_str(&render_summary(&found.summary));
        for (title, lines) in [
            ("rows deferred to a task (todo:<TASK>)", &found.deferred),
            ("row counts waived (rows:computed)", &found.computed),
            ("rows merged into another test (merged:)", &found.merged),
        ] {
            if !lines.is_empty() {
                let _ = writeln!(stdout, "\n{title}: {}", lines.len());
                for line in lines {
                    let _ = writeln!(stdout, "  {line}");
                }
            }
        }
    }
    for note in &found.notes {
        let _ = writeln!(stderr, "anthology-dev ledger: note: {note}");
    }
    for problem in &found.problems {
        let _ = writeln!(stderr, "anthology-dev ledger: {problem}");
    }
    let ids: usize = found
        .summary
        .iter()
        .map(|(_, c)| c.get("ids").copied().unwrap_or(0))
        .sum();
    let code = if found.problems.is_empty() {
        let _ = writeln!(
            stdout,
            "ledger: ok ({ids} ids in {} modules)",
            found.summary.len()
        );
        0
    } else {
        let _ = writeln!(
            stderr,
            "anthology-dev ledger: {} problems",
            found.problems.len()
        );
        1
    };
    Output {
        stdout: stdout.into_bytes(),
        stderr: stderr.into_bytes(),
        code,
    }
}

