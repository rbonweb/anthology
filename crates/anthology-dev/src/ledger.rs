/// The ledger files on disk, by module.
fn ledger_files(root: &Path) -> Result<BTreeMap<String, PathBuf>, String> {
    let dir = root.join(LEDGER_DIR);
    let mut out = BTreeMap::new();
    let entries = match fs::read_dir(&dir) {
        Ok(e) => e,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(out),
        Err(e) => return Err(format!("cannot read {}: {e}", dir.display())),
    };
    for entry in entries {
        let entry = entry.map_err(|e| format!("cannot read {}: {e}", dir.display()))?;
        let name = entry.file_name().to_string_lossy().into_owned();
        if let Some(module) = name.strip_suffix(".tsv") {
            out.insert(module.to_string(), entry.path());
        }
    }
    Ok(out)
}

/// Difftest surface names (`pub const NAME: &str = "…";` in `crates/difftest/src/surfaces/`).
fn surface_names(root: &Path) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let dir = root.join("crates/difftest/src/surfaces");
    let Ok(entries) = fs::read_dir(dir) else {
        return out;
    };
    for entry in entries.flatten() {
        let Ok(text) = fs::read_to_string(entry.path()) else {
            continue;
        };
        for line in text.lines() {
            if let Some(rest) = line.trim().strip_prefix("pub const NAME: &str = \"")
                && let Some(name) = rest.strip_suffix("\";")
            {
                out.insert(name.to_string());
            }
        }
    }
    out
}

/// The `crates/<crate>/<sub>/<name>` paths that exist, for every crate.
fn crate_files(root: &Path, sub: &str, name: &str) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let Ok(entries) = fs::read_dir(root.join("crates")) else {
        return out;
    };
    let mut dirs: Vec<PathBuf> = entries.flatten().map(|e| e.path()).collect();
    dirs.sort();
    for dir in dirs {
        let path = dir.join(sub).join(name);
        if path.is_file() {
            out.push(path);
        }
    }
    out
}

/// Rust rows per id in `crates/*/tests/data/<module>.jsonl`: the first `"py": "<id>"` of a line.
fn rust_rows(root: &Path, module: &str) -> HashMap<String, u64> {
    let mut out = HashMap::new();
    let key = "\"py\"";
    for path in crate_files(root, "tests/data", &format!("{module}.jsonl")) {
        let Ok(text) = fs::read_to_string(&path) else {
            continue;
        };
        for line in text.lines() {
            let Some(at) = line.find(key) else { continue };
            let rest = line[at + key.len()..].trim_start();
            let Some(rest) = rest.strip_prefix(':') else {
                continue;
            };
            let Some(rest) = rest.trim_start().strip_prefix('"') else {
                continue;
            };
            if let Some(end) = rest.find('"') {
                *out.entry(rest[..end].to_string()).or_insert(0) += 1;
            }
        }
    }
    out
}

/// Checks a `ported` row's `rust_test`. `cache` holds scanned files.
fn check_rust_test(
    root: &Path,
    row: &Row,
    cache: &mut HashMap<PathBuf, Result<Vec<rust_scan::TestFn>, String>>,
) -> Option<String> {
    let target = row.rust_test.as_str();
    if target.is_empty() {
        return Some("is ported but names no Rust test".into());
    }
    let Some((file, path)) = target.split_once(".rs::") else {
        return Some(format!(
            "rust_test {target:?} is not `<file.rs>::<mod>::…::<fn>`"
        ));
    };
    let file = format!("{file}.rs");
    let relative = Path::new(&file);
    let safe = relative.is_relative()
        && relative
            .components()
            .all(|c| matches!(c, std::path::Component::Normal(_)));
    if !safe || !file.starts_with("crates/") {
        return Some(format!(
            "rust_test file {file:?} is not a path under crates/"
        ));
    }
    let segments: Vec<String> = path.split("::").map(str::to_string).collect();
    if segments.iter().any(|s| !is_identifier(s)) {
        return Some(format!(
            "rust_test {target:?} has an empty or invalid path segment"
        ));
    }
    let method = method_of(&row.id);
    if segments.last().map(String::as_str) != Some(method) {
        return Some(format!(
            "rust_test {target:?} must keep the Python method name {method} (plan §0.1.5)"
        ));
    }
    let full = root.join(relative);
    let scanned = cache
        .entry(full.clone())
        .or_insert_with(|| read(&full).map(|text| rust_scan::scan(&text)));
    let tests = match scanned {
        Ok(t) => t,
        Err(_) => return Some(format!("Rust test file {file} is missing")),
    };
    match tests.iter().find(|t| t.path == segments) {
        None => Some(format!(
            "Rust test {target} is missing (no #[test] fn there)"
        )),
        Some(t) if t.ignored => Some(format!("Rust test {target} is #[ignore]d")),
        Some(t) if t.gated => Some(format!(
            "Rust test {target} is behind a platform cfg (it must run on Linux and macOS)"
        )),
        Some(_) => None,
    }
}

