//! `anthology-dev ledger`: the test ledger (design §13.3; plan §0.1.4, §0.2.2). Owner: F4a.
//!
//! The ledger maps every Python test run id to its Rust fate, so no test is dropped silently.
//!
//! - `port/python-test-ids.txt`: every run id of `python -m unittest discover -s tests`, sorted.
//! - `port/python-test-rows.tsv`: `python_id<TAB>rows`, the `subTest` table rows of each id.
//! - `port/regex-inventory.tsv`: every lookaround or backreference pattern (plan GC-16).
//! - `port/ledger/<python_module>.tsv`: one file per Python module, so parallel lanes never edit
//!   the same file. A row is `python_id<TAB>status[<TAB>rust_test[<TAB>note]]`; `#` lines are
//!   comments.
//!
//! The first three are generated by `port/extract/{test_ids,rows,regex_inventory}.py` in the
//! pinned Python image. `ci/jobs/ledger.sh` does that, captures `cargo test --workspace --locked
//! -- --list` and `-- --list --ignored` (plain and `--all-features`) in the Rust image, and passes
//! the directory as `--fresh DIR`: `check` compares it with the committed files and requires
//! every `ported` target in a listing and in no ignored listing; `ids --write` copies it over the committed files. `check` refuses to
//! run without `--fresh` unless `--no-fresh` says so.
//!
//! Statuses:
//! - `ported`: `rust_test` is `crates/<crate>/<file.rs>::<mod>::…::<fn>`, named like the Python
//!   method (plan §0.1.5): a `#[test]` that cargo lists, not ignored, behind no `cfg` but `test`
//!   or a feature, in a file `mod` declarations reach. Each target is claimed by one row only;
//!   one Rust test covering several Python tests says so with `merged:`. A note
//!   `platform:<linux|macos>` lets the test run on that platform only, and only for a
//!   (python_id, platform) pair in `port/ledger/platform-exceptions.tsv` (controller-owned);
//! - `merged:<python_id>`: covered by that id's test, which must be `ported` and in the same
//!   module, with a note saying how (listed in `--report`), and never `platform:`-limited;
//! - `golden:<corpus>`: a difftest surface (plan §1.4) or `crates/*/tests/golden/<corpus>.jsonl`;
//! - `dropped:py-compat`, `dropped:python-runtime`, `dropped:superseded:F-<1..20>`, with a note;
//! - `todo`, or `todo:<TASK>` when a module's ids are split between tasks; `<TASK>` must own the
//!   module in plan §5 ([`MODULE_OWNERS`]). A `--files` check fails on every deferred row unless
//!   `--task` names the task being checked (an owner of every `--files` module); then only that
//!   task's deferred rows fail.
//!
//! A `ported` or `merged:` id with table rows needs a Rust row for each Python row: lines tagged
//! `"py": "<id>"` with distinct `"row": 0..n-1`, in `tests/data/<python_module>.jsonl` of the
//! target's crate. A note `rows:computed <reason>` waives that when the Rust test derives the same
//! rows from repository data at run time; `--report` lists every such row.

