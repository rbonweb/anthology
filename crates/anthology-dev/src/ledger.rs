/// Runs `anthology-dev ledger …`; `args` are the arguments after `ledger`.
pub fn run(args: &[OsString], stdin: &mut dyn Read) -> Output {
    let _ = stdin;
    match args.first().and_then(|a| a.to_str()) {
        Some("check") => match CheckArgs::parse(&args[1..]) {
            Ok(a) => check(&a),
            Err(e) => usage(&e),
        },
        Some("ids") => match IdsArgs::parse(&args[1..]) {
            Ok(a) => ids(&a),
            Err(e) => usage(&e),
        },
        Some(other) => usage(&format!("unknown ledger subcommand: {other}")),
        None => usage("ledger needs one of: check, ids"),
    }
}

fn usage(message: &str) -> Output {
    Output {
        stderr: format!("anthology-dev ledger: {message}\n{USAGE}\n").into_bytes(),
        code: 2,
        ..Output::default()
    }
}

fn fail(message: &str) -> Output {
    Output {
        stderr: format!("anthology-dev ledger: {message}\n").into_bytes(),
        code: 1,
        ..Output::default()
    }
}

