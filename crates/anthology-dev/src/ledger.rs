fn read(path: &Path) -> Result<String, String> {
    fs::read_to_string(path).map_err(|e| format!("cannot read {}: {e}", path.display()))
}

/// The data lines of a TSV or list file: no blank lines, no `#` comments.
fn data_lines(text: &str) -> impl Iterator<Item = (usize, &str)> {
    text.lines()
        .enumerate()
        .map(|(n, l)| (n + 1, l.strip_suffix('\r').unwrap_or(l)))
        .filter(|(_, l)| !l.trim().is_empty() && !l.starts_with('#'))
}

fn is_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    chars
        .next()
        .is_some_and(|c| c == '_' || c.is_ascii_alphabetic())
        && chars.all(|c| c == '_' || c.is_ascii_alphanumeric())
}

/// `module.Class.method` (a class may be nested: more than three parts).
fn is_python_id(id: &str) -> bool {
    let parts: Vec<&str> = id.split('.').collect();
    parts.len() >= 3 && parts.iter().all(|p| is_identifier(p))
}

fn module_of(id: &str) -> &str {
    id.split('.').next().unwrap_or(id)
}

fn method_of(id: &str) -> &str {
    id.rsplit('.').next().unwrap_or(id)
}

fn is_task(task: &str) -> bool {
    TASKS.contains(&task)
}

/// The committed (or fresh) id list: sorted, unique, well-formed.
pub fn parse_ids(text: &str, what: &str, problems: &mut Vec<String>) -> Vec<String> {
    let mut ids: Vec<String> = Vec::new();
    for (n, line) in data_lines(text) {
        if !is_python_id(line) {
            problems.push(format!("{what}:{n}: not a Python test id: {line:?}"));
            continue;
        }
        if let Some(prev) = ids.last()
            && prev.as_str() >= line
        {
            problems.push(format!(
                "{what}:{n}: {line} is out of order or repeated (the list is sorted and unique)"
            ));
        }
        ids.push(line.to_string());
    }
    ids
}

/// `python_id<TAB>rows` lines.
pub fn parse_rows(text: &str, what: &str, problems: &mut Vec<String>) -> BTreeMap<String, u64> {
    let mut rows = BTreeMap::new();
    for (n, line) in data_lines(text) {
        let parsed = line
            .split_once('\t')
            .and_then(|(id, count)| Some((id, count.parse::<u64>().ok()?)));
        match parsed {
            Some((id, count)) if is_python_id(id) && count > 0 => {
                if rows.insert(id.to_string(), count).is_some() {
                    problems.push(format!("{what}:{n}: {id} is repeated"));
                }
            }
            _ => problems.push(format!("{what}:{n}: not `python_id<TAB>rows`: {line:?}")),
        }
    }
    rows
}

/// Regex inventory rows (`file<TAB>where<TAB>constructs<TAB>pattern`), as whole lines.
pub fn parse_inventory(text: &str, what: &str, problems: &mut Vec<String>) -> BTreeSet<String> {
    let mut rows = BTreeSet::new();
    for (n, line) in data_lines(text) {
        let fields: Vec<&str> = line.split('\t').collect();
        if fields.len() != 4 || fields[..3].iter().any(|f| f.is_empty()) {
            problems.push(format!(
                "{what}:{n}: not `file<TAB>where<TAB>constructs<TAB>pattern`: {line:?}"
            ));
            continue;
        }
        if !rows.insert(line.to_string()) {
            problems.push(format!("{what}:{n}: repeated row"));
        }
    }
    rows
}

