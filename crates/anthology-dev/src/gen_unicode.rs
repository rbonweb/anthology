//! `anthology-dev gen-unicode`: pycompat's Unicode tables (design §12, plan GC-16). Owner: P1.
//!
//! ```text
//! python3 -I port/difftest/oracle/unicode_dump.py > dump.json        # pinned 3.12 image
//! anthology-dev gen-unicode < dump.json > crates/anthology-pycompat/src/tables.rs
//! ```
//!
//! Reads the dump (one JSON object; its format is in `unicode_dump.py`) on stdin and writes the
//! Rust source of `anthology_pycompat::tables` on stdout. The output depends only on the dump,
//! and it is already in its `cargo fmt` form (every table is `#[rustfmt::skip]`).

use std::ffi::OsString;
use std::fmt::Write as _;
use std::io::Read;

use anthology_pycompat::json::{self, Value};

use crate::Output;

/// The boolean tables: (dump name, Rust static, what it is).
const RANGES: &[(&str, &str, &str)] = &[
    ("isspace", "SPACE", "`str.isspace`"),
    ("isdecimal", "DECIMAL", "`str.isdecimal`"),
    ("isdigit", "DIGIT", "`str.isdigit`"),
    ("isalpha", "ALPHA", "`str.isalpha`"),
    ("isalnum", "ALNUM", "`str.isalnum`"),
    ("isprintable", "PRINTABLE", "`str.isprintable`"),
    (
        "word",
        "WORD",
        "what a str pattern's `\\w` matches: `isalnum() or c == \"_\"`",
    ),
    (
        "case_ignorable",
        "CASE_IGNORABLE",
        "Case_Ignorable, as CPython's `str.lower` uses it for Final_Sigma",
    ),
    (
        "cased",
        "CASED",
        "Cased, for the characters that are not case-ignorable (the only ones Final_Sigma asks about)",
    ),
    (
        "sre_cased",
        "SRE_CASED",
        "`_sre.unicode_iscased`: what `re.IGNORECASE` folds",
    ),
];

/// Runs `anthology-dev gen-unicode`; `args` are the arguments after `gen-unicode`.
pub fn run(args: &[OsString], stdin: &mut dyn Read) -> Output {
    if !args.is_empty() {
        return Output::usage("gen-unicode takes no arguments (the dump is on stdin)");
    }
    let mut text = String::new();
    if let Err(e) = stdin.read_to_string(&mut text) {
        return fail(&format!("cannot read the dump: {e}"));
    }
    match generate(&text) {
        Ok(src) => Output {
            stdout: src.into_bytes(),
            ..Output::default()
        },
        Err(e) => fail(&e),
    }
}

fn fail(msg: &str) -> Output {
    Output {
        stderr: format!("anthology-dev gen-unicode: {msg}\n").into_bytes(),
        code: 1,
        ..Output::default()
    }
}

/// The Rust source for a dump.
pub fn generate(dump: &str) -> Result<String, String> {
    let v = json::loads(dump).map_err(|e| format!("the dump is not JSON: {}", e.msg))?;
    let top = v.as_object().ok_or("the dump is not an object")?;
    let version = top
        .get("version")
        .and_then(Value::as_str)
        .ok_or("no version")?;
    let ranges = top
        .get("ranges")
        .and_then(Value::as_object)
        .ok_or("no ranges")?;

    let mut out = String::new();
    out.push_str(&format!(
        "//! Generated by `anthology-dev gen-unicode` from `port/difftest/oracle/unicode_dump.py`\n\
         //! (CPython 3.12, Unicode {version}). Do not edit: regenerate (design §12, plan GC-16).\n\
         //!\n\
         //! Every table is sorted by code point and holds inclusive runs; surrogates are never in one.\n\
         \n\
         /// `unicodedata.unidata_version` of the interpreter that made the dump.\n\
         pub const UNICODE_VERSION: &str = {version:?};\n"
    ));

    let mut word = Vec::new();
    let mut space = Vec::new();
    let mut decimal = Vec::new();
    for (key, name, doc) in RANGES {
        let runs = pairs(
            ranges.get(key).ok_or_else(|| format!("no ranges.{key}"))?,
            key,
        )?;
        out.push_str(&format!(
            "\n/// {doc}.\n#[rustfmt::skip]\npub static {name}: &[(u32, u32)] = &["
        ));
        list(
            &mut out,
            runs.iter().map(|(a, b)| format!("({a:#x}, {b:#x})")),
        );
        out.push_str("];\n");
        match *key {
            "word" => word = runs,
            "isspace" => space = runs,
            "isdecimal" => decimal = runs,
            _ => {}
        }
    }

    // unicodedata.category: the names, then (lo, hi, index) runs; a gap is "Cn".
    let cats = top
        .get("category")
        .and_then(Value::as_array)
        .ok_or("no category")?;
    let mut names: Vec<String> = Vec::new();
    let mut runs = Vec::new();
    for item in cats {
        let (a, b, rest) = triple(item, "category")?;
        let name = rest.as_str().ok_or("category: a name is not a string")?;
        if name.len() != 2 || name == "Cn" {
            return Err(format!("category: bad name {name:?}"));
        }
        let idx = match names.iter().position(|n| n == name) {
            Some(i) => i,
            None => {
                names.push(name.to_string());
                names.len() - 1
            }
        };
        runs.push((a, b, idx));
    }
    check_sorted(runs.iter().map(|r| (r.0, r.1)), "category")?;
    out.push_str("\n/// The `unicodedata.category` names that [`CATEGORY`] indexes.\n#[rustfmt::skip]\npub static CATEGORY_NAMES: &[&str] = &[");
    list(&mut out, names.iter().map(|n| format!("{n:?}")));
    out.push_str("];\n");
    out.push_str("\n/// `unicodedata.category` runs: `(lo, hi, index into CATEGORY_NAMES)`; a code point in none is `Cn`.\n#[rustfmt::skip]\npub static CATEGORY: &[(u32, u32, u8)] = &[");
    list(
        &mut out,
        runs.iter()
            .map(|(a, b, i)| format!("({a:#x}, {b:#x}, {i})")),
    );
    out.push_str("];\n");

    // unicodedata.decimal: (lo, hi, value at lo), counting up by one.
    let decs = top
        .get("decimal")
        .and_then(Value::as_array)
        .ok_or("no decimal")?;
    let mut drun = Vec::new();
    for item in decs {
        let (a, b, rest) = triple(item, "decimal")?;
        let v = rest
            .as_i64()
            .filter(|v| (0..=9).contains(v))
            .ok_or("decimal: a value is not 0..=9")?;
        if v + i64::from(b - a) > 9 {
            return Err(format!("decimal: the run at {a:#x} passes 9"));
        }
        drun.push((a, b, v));
    }
    check_sorted(drun.iter().map(|r| (r.0, r.1)), "decimal")?;
    out.push_str("\n/// `unicodedata.decimal` runs: `(lo, hi, value of lo)`; the value counts up by one.\n#[rustfmt::skip]\npub static DECIMAL_VALUE: &[(u32, u32, u8)] = &[");
    list(
        &mut out,
        drun.iter()
            .map(|(a, b, v)| format!("({a:#x}, {b:#x}, {v})")),
    );
    out.push_str("];\n");

    // str.lower: one character, or more.
    let lows = top
        .get("lower")
        .and_then(Value::as_array)
        .ok_or("no lower")?;
    let mut single = Vec::new();
    let mut multi = Vec::new();
    let mut last = None;
    for item in lows {
        let pair = item
            .as_array()
            .filter(|p| p.len() == 2)
            .ok_or("lower: not a pair")?;
        let cp = code_point(&pair[0], "lower")?;
        if last.is_some_and(|l| l >= cp) {
            return Err("lower: not sorted".into());
        }
        last = Some(cp);
        let s = pair[1].as_str().ok_or("lower: not a string")?;
        let mut cs = s.chars();
        match (cs.next(), cs.next()) {
            (Some(c), None) => single.push((cp, u32::from(c))),
            (Some(_), Some(_)) => multi.push((cp, s.to_string())),
            _ => return Err(format!("lower: empty mapping for {cp:#x}")),
        }
    }
    out.push_str("\n/// `str.lower` of the code points that map to one other character: `(cp, lower)`.\n#[rustfmt::skip]\npub static LOWER: &[(u32, u32)] = &[");
    list(
        &mut out,
        single.iter().map(|(a, b)| format!("({a:#x}, {b:#x})")),
    );
    out.push_str("];\n");
    out.push_str("\n/// `str.lower` of the code points that map to more than one character.\n#[rustfmt::skip]\npub static LOWER_MULTI: &[(u32, &str)] = &[");
    list(
        &mut out,
        multi
            .iter()
            .map(|(a, s)| format!("({a:#x}, {})", rust_str(s))),
    );
    out.push_str("];\n");

    // re.IGNORECASE: the simple lowercase where it is not str.lower's, and the extra cases.
    let sre = top
        .get("sre_lower")
        .and_then(Value::as_array)
        .ok_or("no sre_lower")?;
    let mut sre_lower = Vec::new();
    for item in sre {
        let p = item
            .as_array()
            .filter(|p| p.len() == 2)
            .ok_or("sre_lower: not a pair")?;
        let cp = code_point(&p[0], "sre_lower")?;
        if !multi.iter().any(|(m, _)| *m == cp) {
            return Err(format!(
                "sre_lower: {cp:#x} has a one-character str.lower, which must be its simple lowercase"
            ));
        }
        sre_lower.push((cp, code_point(&p[1], "sre_lower")?));
    }
    if sre_lower.len() != multi.len() {
        return Err("sre_lower: every multi-character lowercase needs its simple one".into());
    }
    out.push_str("\n/// `_sre.unicode_tolower` where it is not [`LOWER`]'s (the characters in [`LOWER_MULTI`]).\n#[rustfmt::skip]\npub static SRE_LOWER: &[(u32, u32)] = &[");
    list(
        &mut out,
        sre_lower.iter().map(|(a, b)| format!("({a:#x}, {b:#x})")),
    );
    out.push_str("];\n");
    let extra = top
        .get("extra_cases")
        .and_then(Value::as_array)
        .ok_or("no extra_cases")?;
    let mut rows = Vec::new();
    let mut prev = None;
    for item in extra {
        let p = item
            .as_array()
            .filter(|p| p.len() == 2)
            .ok_or("extra_cases: not a pair")?;
        let k = code_point(&p[0], "extra_cases")?;
        if prev.is_some_and(|q| q >= k) {
            return Err("extra_cases: not sorted".into());
        }
        prev = Some(k);
        let vs = p[1].as_array().ok_or("extra_cases: not a list")?;
        let vs: Vec<String> = vs
            .iter()
            .map(|v| code_point(v, "extra_cases").map(|n| format!("{n:#x}")))
            .collect::<Result<_, _>>()?;
        rows.push(format!("({k:#x}, &[{}])", vs.join(", ")));
    }
    out.push_str("\n/// `re._casefix._EXTRA_CASES`: other lowercase letters with the same uppercase.\n#[rustfmt::skip]\npub static EXTRA_CASES: &[(u32, &[u32])] = &[");
    list(&mut out, rows.into_iter());
    out.push_str("];\n");

    // The str-pattern classes for pycompat::re.
    for (stem, runs, what, not) in [
        ("WORD", &word, "`\\w`", "`\\W`"),
        ("SPACE", &space, "`\\s`", "`\\S`"),
        ("DECIMAL", &decimal, "`\\d`", "`\\D`"),
    ] {
        let mac = format!("{}_items", stem.to_ascii_lowercase());
        out.push_str(&format!(
            "\n// The inside of a `regex`/`fancy-regex` character class equal to a str pattern's {what}.\n#[rustfmt::skip]\nmacro_rules! {mac} {{ () => {{ concat!("
        ));
        list(&mut out, runs.iter().map(|&(a, b)| class_item(a, b)));
        out.push_str(&format!(
            ") }}; }}\n\
             /// The inside of a character class equal to a str pattern's {what}.\n\
             pub const {stem}_ITEMS: &str = {mac}!();\n\
             /// A character class equal to a str pattern's {what}.\n\
             pub const {stem}_CLASS: &str = concat!(\"[\", {mac}!(), \"]\");\n\
             /// A character class equal to a str pattern's {not}.\n\
             pub const NOT_{stem}_CLASS: &str = concat!(\"[^\", {mac}!(), \"]\");\n"
        ));
    }
    Ok(out)
}

/// Writes `items` as list entries, a few per line, each followed by a comma.
fn list(out: &mut String, items: impl Iterator<Item = String>) {
    let mut line = 0usize;
    let mut any = false;
    for item in items {
        if !any || line + item.len() + 2 > 96 {
            out.push_str("\n    ");
            line = 4;
        } else {
            out.push(' ');
            line += 1;
        }
        out.push_str(&item);
        out.push(',');
        line += item.len() + 1;
        any = true;
    }
    if any {
        out.push('\n');
    }
}

fn code_point(v: &Value, what: &str) -> Result<u32, String> {
    let n = v
        .as_i64()
        .ok_or_else(|| format!("{what}: a code point is not an int"))?;
    let n = u32::try_from(n).map_err(|_| format!("{what}: bad code point {n}"))?;
    if n > 0x10_FFFF || (0xD800..=0xDFFF).contains(&n) {
        return Err(format!("{what}: bad code point {n:#x}"));
    }
    Ok(n)
}

fn pairs(v: &Value, what: &str) -> Result<Vec<(u32, u32)>, String> {
    let arr = v.as_array().ok_or_else(|| format!("{what}: not a list"))?;
    let mut out = Vec::with_capacity(arr.len());
    for item in arr {
        let p = item
            .as_array()
            .filter(|p| p.len() == 2)
            .ok_or_else(|| format!("{what}: not a pair"))?;
        out.push((code_point(&p[0], what)?, code_point(&p[1], what)?));
    }
    check_sorted(out.iter().copied(), what)?;
    Ok(out)
}

fn triple<'a>(item: &'a Value, what: &str) -> Result<(u32, u32, &'a Value), String> {
    let p = item
        .as_array()
        .filter(|p| p.len() == 3)
        .ok_or_else(|| format!("{what}: not a triple"))?;
    Ok((code_point(&p[0], what)?, code_point(&p[1], what)?, &p[2]))
}

fn check_sorted(runs: impl Iterator<Item = (u32, u32)>, what: &str) -> Result<(), String> {
    let mut prev: Option<u32> = None;
    for (a, b) in runs {
        if a > b || prev.is_some_and(|p| p >= a) {
            return Err(format!("{what}: runs not sorted and disjoint at {a:#x}"));
        }
        if a <= 0xDFFF && b >= 0xD800 {
            return Err(format!("{what}: a run at {a:#x} holds surrogates"));
        }
        prev = Some(b);
    }
    Ok(())
}

/// `"\u{…}"` escapes for everything outside printable ASCII.
fn rust_str(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' | '\\' => {
                out.push('\\');
                out.push(c);
            }
            ' '..='~' => out.push(c),
            _ => {
                let _ = write!(out, "\\u{{{:x}}}", u32::from(c));
            }
        }
    }
    out.push('"');
    out
}

/// One class item as a Rust string literal: `"\\x{41}"` or `"\\x{41}-\\x{5a}"`.
fn class_item(a: u32, b: u32) -> String {
    if a == b {
        format!("\"\\\\x{{{a:x}}}\"")
    } else {
        format!("\"\\\\x{{{a:x}}}-\\\\x{{{b:x}}}\"")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const DUMP: &str = r#"{"category": [[65, 90, "Lu"], [97, 122, "Ll"], [931, 931, "Lu"]],
        "decimal": [[48, 57, 0]], "lower": [[65, "a"], [304, "i̇"], [931, "σ"]],
        "sre_lower": [[304, 105]], "extra_cases": [[105, [305]], [305, [105]]],
        "ranges": {"case_ignorable": [[39, 39]], "cased": [[65, 90], [97, 122]],
        "isalnum": [[48, 57], [65, 90]], "isalpha": [[65, 90]], "isdecimal": [[48, 57]],
        "isdigit": [[48, 57]], "isprintable": [[32, 126]], "isspace": [[9, 13], [32, 32]],
        "word": [[48, 57], [65, 90], [95, 95]], "sre_cased": [[65, 90], [97, 122]]},
        "version": "15.0.0"}"#;

    #[test]
    fn a_dump_becomes_the_tables() {
        let src = generate(DUMP).unwrap();
        assert!(src.contains("pub const UNICODE_VERSION: &str = \"15.0.0\";"));
        assert!(
            src.contains("pub static SPACE: &[(u32, u32)] = &[\n    (0x9, 0xd), (0x20, 0x20),\n];")
        );
        assert!(src.contains("pub static CATEGORY_NAMES: &[&str] = &[\n    \"Lu\", \"Ll\",\n];"));
        assert!(src.contains("(0x41, 0x5a, 0), (0x61, 0x7a, 1), (0x3a3, 0x3a3, 0),"));
        assert!(src.contains(
            "pub static LOWER_MULTI: &[(u32, &str)] = &[\n    (0x130, \"i\\u{307}\"),\n];"
        ));
        assert!(src.contains("(0x41, 0x61), (0x3a3, 0x3c3),"));
        assert!(src.contains("\"\\\\x{30}-\\\\x{39}\", \"\\\\x{41}-\\\\x{5a}\", \"\\\\x{5f}\","));
        // Deterministic.
        assert_eq!(src, generate(DUMP).unwrap());
    }

    #[test]
    fn a_bad_dump_is_refused() {
        assert!(generate("[]").is_err());
        let unsorted = DUMP.replace("[[9, 13], [32, 32]]", "[[32, 32], [9, 13]]");
        assert!(generate(&unsorted).unwrap_err().contains("not sorted"));
        let surrogate = DUMP.replace("[[39, 39]]", "[[55296, 55296]]");
        assert!(generate(&surrogate).unwrap_err().contains("bad code point"));
    }

    #[test]
    fn the_command_reads_stdin_and_takes_no_arguments() {
        let out = run(&[], &mut DUMP.as_bytes());
        assert_eq!(out.code, 0);
        let out = run(&["x".into()], &mut DUMP.as_bytes());
        assert_eq!(out.code, 2);
        let out = run(&[], &mut "{".as_bytes());
        assert_eq!(out.code, 1);
    }
}
